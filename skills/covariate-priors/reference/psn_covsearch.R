# ---------------------------------------------------------------------------
# Covariate-search executor (F5/F11, Codex round 8).
#
# The uncertainty lane's .psn_run() gates on .PSN_UNCERTAINTY_TOOL_UNIT, whose
# map holds only bootstrap/sir/llp. Routing the covariate-search tools
# (scmplus, boot_scm, xv_scm, lasso, frem) through it meant every one was
# refused as an "unknown PsN tool" BEFORE it could run — this lane could not
# execute at all. The remedy is a DEDICATED executor here, mapping every
# covariate-search tool to this lane's own intended-use unit (psn_covsearch)
# and gating through .psn_covsearch_gate() before any system2 — NOT an edit to
# the psn-uncertainty map, whose scope is genuinely bootstrap/sir/llp.
#
# The tool set is exactly the tools the reference_psn_* entry points invoke;
# an unmapped tool is a hard stop (never an ungated run), the same discipline
# as .psn_run().
.PSN_COVSEARCH_TOOL_UNIT <- c(scmplus = "psn_covsearch",
                              boot_scm = "psn_covsearch",
                              xv_scm = "psn_covsearch",
                              lasso = "psn_covsearch",
                              frem = "psn_covsearch")

.psn_covsearch_run <- function(workdir, tool, args, executor, repo_root,
                               invocation = NULL) {
  unit <- unname(.PSN_COVSEARCH_TOOL_UNIT[tool])
  if (length(tool) != 1 || is.na(unit)) {
    stop(".psn_covsearch_run: unknown PsN covariate-search tool '", tool,
         "' — the runner gates on a mapped intended-use unit before ",
         "executing, and refuses an unmapped tool rather than run ungated. ",
         "Known tools: ",
         paste(names(.PSN_COVSEARCH_TOOL_UNIT), collapse = ", "), ".",
         call. = FALSE)
  }
  .psn_covsearch_gate()
  exec <- executor
  if (!grepl("^/", exec)) exec <- file.path(repo_root, exec)
  exec <- normalizePath(exec, mustWork = TRUE)
  if (!dir.exists(workdir)) {
    stop("workdir does not exist: ", workdir, call. = FALSE)
  }
  full <- c(normalizePath(workdir, mustWork = TRUE), tool, args)
  run_env <- if (is.null(invocation)) character(0) else
    paste0("PMX_INVOCATION_ID=", invocation$name)
  out <- suppressWarnings(system2(exec, shQuote(full), env = run_env,
                                  stdout = TRUE, stderr = TRUE))
  status <- attr(out, "status")
  if (!is.null(status) && status != 0L) {
    stop("PsN ", tool, " failed (exit ", status, "):\n",
         paste(out, collapse = "\n"), call. = FALSE)
  }
  if (is.null(invocation)) return(invisible(out))
  snapshots <- list.files(file.path(workdir, "engine-config-used"),
                          full.names = TRUE)
  snapshots <- snapshots[grepl(invocation$name, basename(snapshots),
                               fixed = TRUE)]
  if (length(snapshots) > 1L)
    stop("PsN ", tool, " invocation ", invocation$name, " produced ",
         length(snapshots), " matching engine-config snapshots; at most one ",
         "invocation-bound snapshot is allowed.", call. = FALSE)
  list(status = status %||% 0L, stdout = out,
       cmd = paste(c(shQuote(exec), shQuote(full)), collapse = " "),
       argv = full,
       config_snapshot = if (length(snapshots)) snapshots[[1]] else NA_character_)
}

# ---------------------------------------------------------------------------
# Prior-list structural control for the config-driven tools.
#
# scmplus / boot_scm / xv_scm all consume an scm config file whose
# [test_relations] section IS the frozen prior list, verbatim, only because
# reference/scm_config.R generated it. A hand-authored config would let an
# off-list covariate into the search, defeating the covariate-priors rule.
# This guard refuses any config that does not carry the generator's
# provenance banner AND a [test_relations] section. It does NOT re-derive
# the list — the generated config is itself the reviewed gate artifact
# (SKILL_SCM.md); this only refuses configs the generator did not write.
.covsearch_assert_generated_config <- function(config_file) {
  if (!file.exists(config_file)) {
    stop("scm config file not found: ", config_file, call. = FALSE)
  }
  txt <- readLines(config_file, warn = FALSE)
  banner <- any(grepl("GENERATED by skills/covariate-priors/reference/scm_config.R",
                      txt, fixed = TRUE))
  has_tr <- any(grepl("^\\s*\\[test_relations\\]", txt))
  if (!banner || !has_tr) {
    stop("refusing to run on ", config_file, ": the config must be GENERATED ",
         "by reference/scm_config.R (banner present) and contain a ",
         "[test_relations] section. [test_relations] is the frozen prior ",
         "list verbatim (skills/covariate-priors/SKILL.md); a hand-authored ",
         "config could admit an off-list covariate. Regenerate with ",
         "reference_scm_config().", call. = FALSE)
  }
  invisible(TRUE)
}

# Extract the base-model path declared on the `model=` line of an scm config,
# so a bootstrapping tool (boot_scm) can run the ID-renumbering precheck on
# it. Returns the model token (relative to workdir unless absolute) or NULL.
.covsearch_config_model <- function(config_file) {
  txt <- readLines(config_file, warn = FALSE)
  ln  <- grep("^\\s*model\\s*=", txt, value = TRUE)
  if (!length(ln)) return(NULL)
  trimws(sub("^\\s*model\\s*=\\s*", "", ln[1]))
}

# Threads/retries operational subset (search tools honor the same two the
# sir path does; tweak_inits/picky flow through the scm sub-runs via the
# full operational translator for the scm-config tools).
.covsearch_thread_args <- function(engine_config) {
  psn <- engine_config$psn %||%
    stop("config/engine.yaml is missing the psn: block.", call. = FALSE)
  a <- character(0)
  if (!is.null(psn$threads)) a <- c(a, paste0("-threads=", psn$threads))
  if (!is.null(psn$retries)) a <- c(a, paste0("-retries=", psn$retries))
  a
}

# ---------------------------------------------------------------------------
# reference_psn_scmplus(...)
#
# scmplus: a drop-in wrapper around scm that reduces runtime via Adaptive
# Scope Reduction — parameter-covariate relations that do not show promise in
# early forward steps are stashed and not retested every step; before the
# backward elimination phase the stashed relations are re-tested
# (scmplus_userguide, master, verified 2026-08-31). It therefore runs the
# house forward-then-backward workflow (SKILL_SCM.md house decision 1) — same
# config file, same [valid_states], same p_forward/p_backward. Deterministic
# search; NO seed. Cannot combine with -linearize (scmplus does not support
# it); if the MAP declared linearized SCM, use scm, not scmplus.
#
# workdir       directory holding the config and base model; MUST be inside a
#               git repo (container mount rule).
# config_file   scm config filename (relative to workdir, or absolute),
#               GENERATED by reference/scm_config.R.
# engine_config parsed config/engine.yaml (list) — operational flags only.
# scope_reduction_steps / retest_stashed / p_cutoff  MAP-declared scmplus
#               scope-reduction knobs; passed through only when non-NULL.
#
# Returns list(cmd, tool, scmlog, raw_results, summary, record). `summary`
# is the scmlog text (verbatim search trail) — parser stub, unverified.
reference_psn_scmplus <- function(workdir, config_file, engine_config,
                                  scope_reduction_steps = NULL,
                                  retest_stashed = NULL, p_cutoff = NULL,
                                  executor = "tools/nonmem_exec.sh",
                                  repo_root = getwd()) {
  .psn_covsearch_gate()
  cfg_path <- if (grepl("^/", config_file)) config_file
              else file.path(workdir, config_file)
  .covsearch_assert_generated_config(cfg_path)

  args <- basename(config_file)
  if (!is.null(scope_reduction_steps))
    args <- c(args, paste0("-scope_reduction_steps=", scope_reduction_steps))
  if (!is.null(retest_stashed))
    args <- c(args, if (isTRUE(retest_stashed)) "-retest_stashed_relations"
                    else "-no-retest_stashed_relations")
  if (!is.null(p_cutoff)) args <- c(args, paste0("-p_cutoff=", p_cutoff))
  args <- c(args, .psn_operational_args(engine_config))

  run_dir <- .psn_new_run_dir(workdir, "scmplus")
  args <- c(args, paste0("-directory=", run_dir$name))
  run <- .psn_covsearch_run(workdir, "scmplus", args, executor, repo_root,
                            invocation = run_dir)

  # Same log/output structure as scm; the scmlog is the verbatim search trail
  # the covariate gate requires. Directory name unverified — locate by file.
  scmlog <- .psn_find_artifact(run_dir, "^scmlog.*\\.txt$", regex = TRUE)
  raw <- .psn_find_artifact(run_dir, "^raw_results.*\\.csv$", regex = TRUE,
                            required = FALSE)
  invocation_manifest <- .psn_write_invocation_manifest(
    run_dir, run, list(scmlog = scmlog, raw_results = raw))
  list(
    cmd    = c("scmplus", args),
    tool   = "scmplus",
    scmlog = scmlog,
    raw_results = raw,
    run_dir = run_dir$path,
    invocation_manifest = invocation_manifest,
    summary = .psn_parse_scmlog(scmlog),
    record = list(tool = "scmplus", config = config_file,
                  scope_reduction_steps = scope_reduction_steps,
                  retest_stashed = retest_stashed, p_cutoff = p_cutoff,
                  operational = engine_config$psn))
}

# ---------------------------------------------------------------------------
# reference_psn_boot_scm(...)
#
# boot_scm: runs scm on multiple bootstrap resamples of the data and reports
# the inclusion frequency of each parameter-covariate relation across
# resamples — a selection-STABILITY assessment, not a new selection. Wraps
# scm (all scm options apply except -base_ofv); consumes the same generated
# config. Stochastic (bootstrap resampling) → seed REQUIRED.
#
# ⚠ Same ID-renumbering corruption class as bootstrap: PsN renumbers
# individuals during resampling, so an ID-based IGNORE/ACCEPT in the base
# model filters the WRONG individuals, silently. The base model is the
# config's model= line; reference_psn_bootstrap_precheck (reused verbatim
# from the uncertainty lane) hard-stops before any container call.
#
# samples       MAP-declared number of bootstrap datasets.
# seed          REQUIRED, MAP-declared; reproducibility of the resampling.
# stratify_on   MAP-declared stratified-resampling column; NULL = unstratified.
# method        MAP-declared "methodA"/"methodB" resampling strategy; NULL =
#               PsN default (methodB). methodA is the nonlinear strategy.
# id_col        ID column for the precheck (default "ID").
#
# Returns list(cmd, tool, inclusion_csv, bs_ids, summary, record).
reference_psn_boot_scm <- function(workdir, config_file, samples, seed,
                                   engine_config, stratify_on = NULL,
                                   method = NULL, id_col = "ID",
                                   executor = "tools/nonmem_exec.sh",
                                   repo_root = getwd()) {
  .psn_covsearch_gate()
  stopifnot(!missing(seed), !missing(samples))
  cfg_path <- if (grepl("^/", config_file)) config_file
              else file.path(workdir, config_file)
  .covsearch_assert_generated_config(cfg_path)

  # ID-renumbering precheck on the base model named in the config.
  model_tok <- .covsearch_config_model(cfg_path)
  if (is.null(model_tok)) {
    stop("boot_scm: could not find a model= line in ", cfg_path,
         "; cannot run the ID-renumbering precheck.", call. = FALSE)
  }
  model_path <- if (grepl("^/", model_tok)) model_tok
                else file.path(workdir, model_tok)
  reference_psn_bootstrap_precheck(model_path, id_col = id_col)

  args <- c(basename(config_file),
            paste0("-samples=", samples),
            paste0("-seed=", seed))
  if (!is.null(stratify_on)) args <- c(args, paste0("-stratify_on=", stratify_on))
  if (!is.null(method))      args <- c(args, paste0("-", method))
  args <- c(args, .psn_operational_args(engine_config))

  run_dir <- .psn_new_run_dir(workdir, "boot_scm")
  args <- c(args, paste0("-directory=", run_dir$name))
  run <- .psn_covsearch_run(workdir, "boot_scm", args, executor, repo_root,
                            invocation = run_dir)

  incl <- .psn_find_artifact(run_dir, "covariate_inclusion.csv")
  bsid <- .psn_find_artifact(run_dir, "bs_ids.csv", required = FALSE)
  invocation_manifest <- .psn_write_invocation_manifest(
    run_dir, run, list(inclusion_csv = incl, bs_ids = bsid))
  list(
    cmd  = c("boot_scm", args),
    tool = "boot_scm",
    inclusion_csv = incl,
    bs_ids = bsid,
    run_dir = run_dir$path,
    invocation_manifest = invocation_manifest,
    summary = .psn_parse_covariate_inclusion(incl),
    record = list(tool = "boot_scm", config = config_file,
                  samples = samples, seed = seed,
                  stratify_on = stratify_on %||% "none (per-MAP)",
                  method = method %||% "methodB (PsN default)",
                  operational = engine_config$psn))
}

