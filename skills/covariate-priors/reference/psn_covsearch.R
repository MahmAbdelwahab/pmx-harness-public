#
# groups        MAP-declared number of CV folds (PsN default 5).
# splits        MAP-declared repetitions with new splits (NULL = default 1).
# stratify_on   MAP-declared fold-stratification column.
#
# Returns list(cmd, tool, xv_ofv, rank_order, pct_inclusion, summary, record).
reference_psn_xv_scm <- function(workdir, config_file, groups, seed,
                                 engine_config, splits = NULL,
                                 stratify_on = NULL,
                                 executor = "tools/nonmem_exec.sh",
                                 repo_root = getwd()) {
  .psn_covsearch_gate()
  stopifnot(!missing(seed), !missing(groups))
  cfg_path <- if (grepl("^/", config_file)) config_file
              else file.path(workdir, config_file)
  .covsearch_assert_generated_config(cfg_path)

  args <- c(basename(config_file),
            paste0("-groups=", groups),
            paste0("-seed=", seed))
  if (!is.null(splits))      args <- c(args, paste0("-splits=", splits))
  if (!is.null(stratify_on)) args <- c(args, paste0("-stratify_on=", stratify_on))
  # -only_successful is documented to interfere with the algorithm; it is
  # never added here.
  args <- c(args, .psn_operational_args(engine_config))

  run_dir <- .psn_new_run_dir(workdir, "xv_scm")
  args <- c(args, paste0("-directory=", run_dir$name))
  run <- .psn_covsearch_run(workdir, "xv_scm", args, executor, repo_root,
                            invocation = run_dir)

  xv_ofv <- .psn_find_artifact(run_dir, "xv_ofv_results.csv")
  rank <- .psn_find_artifact(run_dir, "xv_relation_rank_order.csv",
                             required = FALSE)
  pct <- .psn_find_artifact(run_dir, "xv_percent_inclusion_by_level.csv",
                            required = FALSE)
  invocation_manifest <- .psn_write_invocation_manifest(
    run_dir, run, list(xv_ofv = xv_ofv, rank_order = rank,
                       pct_inclusion = pct))
  list(
    cmd  = c("xv_scm", args),
    tool = "xv_scm",
    xv_ofv = xv_ofv,
    rank_order = rank,
    pct_inclusion = pct,
    run_dir = run_dir$path,
    invocation_manifest = invocation_manifest,
    summary = .psn_parse_xv_ofv(xv_ofv),
    record = list(tool = "xv_scm", config = config_file, groups = groups,
                  splits = splits %||% "1 (PsN default)", seed = seed,
                  stratify_on = stratify_on %||% "none (per-MAP)",
                  operational = engine_config$psn))
}

# ---------------------------------------------------------------------------
# reference_psn_lasso(...)
#
# lasso: simultaneous covariate selection and estimation via the LASSO
# penalty, with the shrinkage tuning parameter (t-value) chosen by
# cross-validation. Addresses the selection bias of stepwise methods.
#
# PRIOR-LIST CONTROL: `relations` IS the search space — it must be the
# relation string GENERATED from the frozen prior list, never hand-authored
# at analysis time (analogous to [test_relations] for scm). Syntax
# (lasso_userguide, verified 2026-08-31): "PAR:COV-type,COV-type,,PAR:..."
# where type is 1=categorical, 2=linear-continuous, 3=piecewise (breakpoint
# optional as "-COV-3-<bp>"). NOTE a house caveat: lasso offers only
# linear/piecewise/categorical parameterizations — NOT the house continuous
# default power form (SKILL.md). Continuous effects are multiplicative when
# -log_scale is on (default). Any departure from the SKILL.md functional-form
# defaults is thereby intrinsic to lasso and must be acknowledged in the MAP.
#
# relations     REQUIRED, non-empty; generated from the prior list.
# t_value       MAP-declared. NULL = the house path (CV selects t over the
#               start_t/stop_t/step_t grid). If a fixed t is declared, it is
#               passed as the search bounds; the EXACT fixing flag is
#               unverified — confirm at first real run.
# seed          REQUIRED, MAP-declared (CV fold assignment is stochastic).
# groups        MAP-declared CV folds (PsN default 5).
# start_t/stop_t/step_t  MAP-declared t-grid when CV-selecting; passed through.
#
# ⚠ Final-model re-estimation: after CV picks the optimal t, lasso re-fits
# the regular model on the full data with the covariate thetas fixed from the
# lasso coefficients, re-estimating the base PK parameters
# (lasso_userguide, verified 2026-08-31). Whether that lasso final model is
# ACCEPTED as-is or the retained relations are re-estimated UNPENALIZED
# (removing lasso shrinkage bias) is a method decision the MAP must declare.
#
# Returns list(cmd, tool, coefficients_csv, raw_results, summary, record).
reference_psn_lasso <- function(workdir, ctl_file, relations, seed,
                                engine_config, t_value = NULL, groups = NULL,
                                start_t = NULL, stop_t = NULL, step_t = NULL,
                                stratify_on = NULL, log_scale = NULL,
                                executor = "tools/nonmem_exec.sh",
                                repo_root = getwd()) {
  .psn_covsearch_gate()
  stopifnot(!missing(seed), !missing(relations))
  if (!is.character(relations) || length(relations) != 1L ||
      !nzchar(trimws(relations))) {
    stop("lasso `relations` must be a single non-empty string generated ",
         "from the frozen prior list (PAR:COV-type,... syntax). It is the ",
         "search space; it is never hand-authored at analysis time ",
         "(skills/covariate-priors/SKILL.md).", call. = FALSE)
  }

  args <- c(basename(ctl_file),
            paste0("-relations=", relations),
            paste0("-seed=", seed))
  if (!is.null(t_value)) {
    # Fixed-t path: pass as the search bounds. EXACT flag unverified —
    # confirm at first real run.
    args <- c(args, paste0("-start_t=", t_value),
                    paste0("-stop_t=", t_value))
  } else {
    if (!is.null(start_t)) args <- c(args, paste0("-start_t=", start_t))
    if (!is.null(stop_t))  args <- c(args, paste0("-stop_t=", stop_t))
    if (!is.null(step_t))  args <- c(args, paste0("-step_t=", step_t))
  }
  if (!is.null(groups))      args <- c(args, paste0("-groups=", groups))
  if (!is.null(stratify_on)) args <- c(args, paste0("-stratify_on=", stratify_on))
  if (!is.null(log_scale))   args <- c(args, if (isTRUE(log_scale)) "-log_scale"
                                             else "-no-log_scale")
  args <- c(args, .covsearch_thread_args(engine_config))

  run_dir <- .psn_new_run_dir(workdir, "lasso")
  args <- c(args, paste0("-directory=", run_dir$name))
  run <- .psn_covsearch_run(workdir, "lasso", args, executor, repo_root,
                            invocation = run_dir)

  coeff <- .psn_find_artifact(run_dir, "lasso_coefficients.csv")
  raw <- .psn_find_artifact(run_dir, "^raw_results.*\\.csv$", regex = TRUE,
                            required = FALSE)
  invocation_manifest <- .psn_write_invocation_manifest(
    run_dir, run, list(coefficients_csv = coeff, raw_results = raw))
  list(
    cmd  = c("lasso", args),
    tool = "lasso",
    coefficients_csv = coeff,
    raw_results = raw,
    run_dir = run_dir$path,
    invocation_manifest = invocation_manifest,
    summary = .psn_parse_lasso_coefficients(coeff),
    record = list(tool = "lasso", relations = relations, seed = seed,
                  t_value = t_value %||% "CV-selected (per-MAP)",
                  groups = groups %||% "5 (PsN default)",
                  stratify_on = stratify_on %||% "none (per-MAP)",
                  operational = engine_config$psn))
}

# ---------------------------------------------------------------------------
# reference_psn_frem(...)
#
# frem: Full Random Effects Modeling — philosophically DIFFERENT from the
# stepwise/penalized methods. There is NO selection: ALL prior-list
# covariates enter simultaneously as random effects, and a full covariance
# between parameters and covariate effects is estimated. This is the
# covariate-priors "prior-anchored full model" alternative path in
# skills/covariate-priors/SKILL.md (correlated covariates, missingness
# robustness) realized in the NONMEM/PsN idiom. Deterministic estimation;
# NO seed.
#
# PRIOR-LIST CONTROL: `covariates` IS the full-model covariate set — it must
# be GENERATED from the frozen prior list (the -covariates flag), never
# hand-authored. There is no [test_relations] because there is no search;
# every listed covariate enters.
#
# frem's own model-building steps (Models 1-4, optionally 5-6 with cholesky)
# run internally; the MAP-declared decisions are:
#   categorical  which covariates are non-ordered categorical (transformed
#                to binary contrasts); passed as -categorical.
#   log          which covariates are log-transformed; passed as -log.
#   skip_omegas  OMEGA blocks excluded from the covariance estimation; a
#                declared structural choice (e.g. IOV blocks).
#   rescale/estimate_means/mu/cholesky  passed through only when declared.
#
# ⚠ Preconditions (frem gotchas): the input model code must NOT already
# contain the listed covariates; no parameter named "FREMTYPE"; cholesky
# needs NONMEM >= 7.3; incompatible with $MSFI. These are asserted at the
# gate against the control stream, not re-derived here.
#
# Returns list(cmd, tool, results_csv, results_json, final_models, summary,
# record). Model 4 in final_models/ is the decisive full-covariance model.
reference_psn_frem <- function(workdir, ctl_file, covariates, engine_config,
                               categorical = NULL, log_cov = NULL,
                               skip_omegas = NULL, rescale = NULL,
                               estimate_means = NULL, mu = NULL,
                               cholesky = NULL,
                               executor = "tools/nonmem_exec.sh",
                               repo_root = getwd()) {
  .psn_covsearch_gate()
  stopifnot(!missing(covariates))
  covariates <- covariates[nzchar(trimws(covariates))]
  if (!length(covariates)) {
    stop("frem `covariates` must be a non-empty set generated from the ",
         "frozen prior list; frem enters ALL of them as random effects ",
         "(no selection). It is never hand-authored at analysis time ",
         "(skills/covariate-priors/SKILL.md).", call. = FALSE)
  }

  args <- c(basename(ctl_file),
            paste0("-covariates=", paste(covariates, collapse = ",")))
  if (!is.null(categorical))
    args <- c(args, paste0("-categorical=", paste(categorical, collapse = ",")))
  if (!is.null(log_cov))
    args <- c(args, paste0("-log=", paste(log_cov, collapse = ",")))
  if (!is.null(skip_omegas))
    args <- c(args, paste0("-skip_omegas=", paste(skip_omegas, collapse = ",")))
  if (!is.null(rescale))
    args <- c(args, if (isTRUE(rescale)) "-rescale" else "-no-rescale")
  if (!is.null(estimate_means))
    args <- c(args, if (isTRUE(estimate_means)) "-estimate_means"
                    else "-no-estimate_means")
  if (!is.null(mu)) args <- c(args, if (isTRUE(mu)) "-mu" else "-no-mu")
  if (!is.null(cholesky))
    args <- c(args, if (isTRUE(cholesky)) "-cholesky" else "-no-cholesky")
  args <- c(args, .covsearch_thread_args(engine_config))

  run_dir <- .psn_new_run_dir(workdir, "frem")
  args <- c(args, paste0("-directory=", run_dir$name))
  run <- .psn_covsearch_run(workdir, "frem", args, executor, repo_root,
                            invocation = run_dir)

  # Pharmpy post-processing writes results.{csv,json}; final_models/ holds
  # Model 4 (decisive). Directory names unverified — locate by file.
  res_csv <- .psn_find_artifact(run_dir, "results.csv", required = FALSE)
  res_json <- .psn_find_artifact(run_dir, "results.json", required = FALSE)
  fm_dir   <- {
    hits <- list.dirs(run_dir$path, recursive = TRUE, full.names = TRUE)
    hits <- hits[basename(hits) == "final_models"]
    hits <- hits[file.info(hits)$mtime >= run_dir$since]
    if (length(hits) > 1L)
      stop("PsN invocation ", run_dir$name, " holds multiple final_models ",
           "directories; the selected output must be unique.", call. = FALSE)
    if (length(hits)) hits[[1]] else NA_character_
  }
  invocation_manifest <- .psn_write_invocation_manifest(
    run_dir, run, list(results_csv = res_csv, results_json = res_json,
                       final_models = fm_dir))
  list(
    cmd  = c("frem", args),
    tool = "frem",
    results_csv  = res_csv,
    results_json = res_json,
    final_models = fm_dir,
    run_dir = run_dir$path,
    invocation_manifest = invocation_manifest,
    summary = if (!is.na(res_csv)) .psn_parse_frem_results(res_csv) else NULL,
    record = list(tool = "frem", covariates = covariates,
                  categorical = categorical %||% "none (per-MAP)",
                  log = log_cov %||% "none (per-MAP)",
                  skip_omegas = skip_omegas %||% "none (per-MAP)",
                  cholesky = cholesky, operational = engine_config$psn))
}

# ---------------------------------------------------------------------------
# mimp / scmreport — available; declare per-analysis before use.
#
# These have NO first-class reference entry point yet; an analysis that needs
# them declares them in the MAP and a reference wrapper is authored at that
# point (same policy as nonpb/mcmp in the uncertainty lane).
#
# mimp  Multiple Imputation of partially missing covariate data — cycles
#       base/regression/imputation/alternative models over -imputations
#       rounds (default 6). Used BEFORE scm/frem when covariate data is
#       incomplete beyond the SKILL.md median/mode imputation. Model roles
#       (base_model, reg_model, mi_model, alt_models, ...) are all explicit;
#       no consolidated decisive artifact — imputations are combined
#       manually. Note: it does NOT relax the SKILL.md missingness policy;
#       the >10% sensitivity-analysis rule still governs.
#
# scmreport  Formatting-only utility downstream of scm/scmplus: extracts
#       inclusion/exclusion decisions and OFV changes from the scm log into a
#       presentable table. No methodological decisions. The verbatim scmlog
#       remains the gate's search-trail source of truth; scmreport is a
#       convenience view, never a substitute for the raw log.

# ---------------------------------------------------------------------------
# Results parsing (stubs). Each reads the decisive artifact with DECLARED
# column expectations. The exact PsN column headers are unverified until a
# real run — parsers read verbatim, do not rename or reshape, and carry an
# "expected_columns" attribute for the gate. A mismatch is reported at the
# gate rather than silently coerced.

# scmlog*.txt — verbatim forward/backward search trail (OFV, p-values,
# retained relations per step). Returned as lines, not a table.
.psn_parse_scmlog <- function(path) {
  if (is.na(path) || !file.exists(path)) return(NULL)
  lines <- readLines(path, warn = FALSE)
  attr(lines, "expected_content") <-
    "per-step OFV, p-value, and retained relations " # unverified — confirm at first real run
  lines
}

# covariate_inclusion.csv — expected: one row per bootstrap sample, one
# column per parameter-covariate relation, 0/1 inclusion; column means are
# the inclusion frequencies (selection stability).
