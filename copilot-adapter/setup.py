def _diff(existing: str, rendered: str, rel: str) -> str:
    return "".join(difflib.unified_diff(
        existing.splitlines(keepends=True), rendered.splitlines(keepends=True),
        fromfile=f"live/{rel}", tofile=f"rendered/{rel}",
    ))


def render_sources(cfg: dict) -> list[str]:
    """Target-relative paths render_all() READS: the agent files, the
    orchestrator role and dispatch-map document, and the skills folders. These
    are what the staging overlay must carry so a virgin bundle can be rendered
    before a single seed asset touches the target."""
    out: list[str] = []
    agents = cfg.get("agents")
    if agents:
        out.append(agents["source_dir"])
        orch = agents.get("orchestrator")
        if orch:
            out.append(orch["role_file"])
            if orch.get("dispatch_map_doc"):
                out.append(orch["dispatch_map_doc"])
    if cfg.get("skills"):
        out.append(cfg["project"].get("skills_dir", "skills"))
    return out


def _copy_into(src: Path, dst: Path) -> None:
    if src.is_dir():
        shutil.copytree(src, dst, dirs_exist_ok=True,
                        ignore=shutil.ignore_patterns(*SKIP_DIRS))
    elif src.is_file():
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)


def render_staged(cfg: dict, profile_dir: Path, target: Path,
                  seed_plan: list[tuple[str, str, Path, Path]]) -> dict[str, str]:
    """Render against an OVERLAY: the target's render sources plus the planned
    seed assets, in a disposable staging directory.

    Rendering reads the target tree, and on a virgin bundle the sources it
    reads from are the very files seeding is about to create. Staging them
    lets the whole plan — seeds, generated files, orphans — be validated
    before the first byte reaches the target, so a refusal anywhere leaves
    nothing behind. The overlay is disposable and outside the target.
    """
    with tempfile.TemporaryDirectory(prefix="copilot-adapter-stage.") as tmp:
        stage = Path(tmp)
        for rel in render_sources(cfg):
            _copy_into(target / rel, stage / rel)
        for verb, rel, src, _dst in seed_plan:
            if verb in ("seed", "overwrite"):
                _copy_into(src, stage / rel)
        return render_all(cfg, profile_dir, stage)


class Commit:
    """All writes of one install, applied atomically as a set.

    ``add`` records a destination and its final bytes. ``apply`` first writes
    every payload to a temporary file beside its destination (nothing visible
    changes if that fails), then ``os.replace``s them in one pass. If a replace
    fails, every destination already replaced is restored from the bytes it
    held before, and the error names what was rolled back.
    """

    def __init__(self) -> None:
        self.entries: list[tuple[Path, bytes, int | None]] = []

    def add(self, dest: Path, data: bytes, mode: int | None = None) -> None:
        self.entries.append((dest, data, mode))

    def apply(self) -> None:
        staged: list[tuple[Path, str, bytes, int | None]] = []
        try:
            for dest, data, mode in self.entries:
                dest.parent.mkdir(parents=True, exist_ok=True)
                fd, tmp = tempfile.mkstemp(prefix=f".{dest.name}.", suffix=".tmp", dir=dest.parent)
                with os.fdopen(fd, "wb") as fh:
                    fh.write(data)
                    fh.flush()
                    os.fsync(fh.fileno())
                if mode is not None:
                    os.chmod(tmp, mode)
                staged.append((dest, tmp, data, mode))
        except OSError as err:
            for _dest, tmp, _data, _mode in staged:
                try:
                    os.unlink(tmp)
                except OSError:
                    pass
            raise ProfileError(f"install aborted before any destination changed: {err}") from None

        replaced: list[tuple[Path, bytes | None, int | None]] = []
        try:
            for dest, tmp, _data, _mode in staged:
                prior = dest.read_bytes() if dest.is_file() else None
                prior_mode = dest.stat().st_mode & 0o7777 if prior is not None else None
                os.replace(tmp, dest)
                replaced.append((dest, prior, prior_mode))
        except OSError as err:
            failed = dest
            for _dest, tmp, _data, _mode in staged[len(replaced):]:
                try:
                    os.unlink(tmp)
                except OSError:
                    pass
            not_restored: list[str] = []
            for dest, prior, prior_mode in reversed(replaced):
                try:
                    if prior is None:
                        dest.unlink()
                    else:
                        _atomic_write_bytes(dest, prior)
                        if prior_mode is not None:
                            os.chmod(dest, prior_mode)
                except OSError:
                    not_restored.append(str(dest))
            msg = (f"install aborted while replacing {failed}: {err}; "
                   f"{len(replaced)} file(s) rolled back to their previous content")
            if not_restored:
                msg += "; COULD NOT RESTORE: " + ", ".join(not_restored)
            raise ProfileError(msg) from None


def _plan_generated(target: Path, outputs: dict[str, str], force: bool
                    ) -> tuple[list[tuple[str, str]], list[str]]:
    """Classify the generated outputs into (verb, rel) plus refusal lines."""
    plan: list[tuple[str, str]] = []
    refusals: list[str] = []
    for rel, content in outputs.items():
        path = target / rel
        if not path.exists():
            plan.append(("create", rel))
            continue
        existing = path.read_text(encoding="utf-8")
        if existing == content:
            plan.append(("unchanged", rel))
        elif force:
            plan.append(("overwrite", rel))
        else:
            plan.append(("conflict", rel))
            refusals.append(
                f"REFUSED: {rel} exists with different content (use --force):\n"
                + _diff(existing, content, rel) + "\n")
    return plan, refusals


def _orphan_refusal(rel: str) -> str:
    return (f"REFUSED: {rel} is an orphaned generated file (no longer expected by the "
            "profile) but its bytes differ from what this generator recorded in "
            f"{INVENTORY_REL}. It was hand-edited, so it is not this tool's to delete: "
            "review it and remove it yourself.\n")


def cmd_install(target: Path, profile_dir: Path, force: bool, dry_run: bool,
                refresh_env: bool = False, reseed: bool = False,
                overwrite_sources: bool = False) -> int:
    """Render the adapter into the target, bootstrapping the payload once.

    Three independent authorities, deliberately not one flag:

    ``--force``
        Overwrite differing GENERATED files (the Copilot layer this tool
        owns). It has no authority over seed assets.
    ``--overwrite-sources``
        Destroy the target's version of a differing SEED ASSET and restore the
        bundle's copy. Explicit and separate, because those files are the
        target's own sources — gate machinery, approved reference code, signed
        manifests — and a user regenerating Copilot files must not be able to
        roll them back by accident.
    ``--reseed``
        Re-enter the seed classification even though
        ``copilot-adapter/.seed-state.json`` already records this bundle.

    Seeding is a one-time bootstrap. The first successful install writes the
    seed state (bundle id, UTC time, per-asset hashes); later installs skip
    seeding entirely while the recorded bundle id matches ``ASSETS.json``. A
    DIFFERENT bundle id — a re-export from newer sources — re-enters the
    three-way classification on its own.

    Global preflight, then atomic commit. The complete plan — seed actions,
    generated-file actions, orphan removals, seed state, inventory — is
    computed and validated against a staging OVERLAY (the target's render
    sources plus the planned seeds, in a disposable directory) before the
    first byte reaches the target. Any refusal aborts with nothing written,
    a virgin bundle included: there is no ordering exception any more. The
    commit writes every file to a temporary path beside its destination and
    ``os.replace``s them in one pass, rolling back on failure.
    """
    # Confirmation is an authorization boundary for the whole refresh. Parse
    # it before seed planning, rendering, inventory reads, or generated-file
    # classification so confirmed or ambiguous YAML cannot permit collateral
    # writes elsewhere in the install.
    harness_path = target / "harness.yaml"
    if harness_path.exists():
        harness_text = harness_path.read_text(encoding="utf-8")
        confirmed = _confirmed(harness_text)
        if refresh_env and confirmed:
            sys.stderr.write(
                f"REFUSED: harness.yaml carries {ENV_CONFIRM_KEY}: true — the "
                "environment is confirmed and the whole refresh is refused.\n"
                f"Set {ENV_CONFIRM_KEY}: false first if this machine really "
                "changed, then run install --refresh-env again.\n")
            return 1

    # ---- preflight: seeding ------------------------------------------------
    seed_plan, seed_refusals, seed_note, seed_state = plan_seed(
        target, reseed=reseed, overwrite_sources=overwrite_sources)
    # A dry run REPORTS the plan, including the conflicts that would refuse it;
    # a real run aborts here, before anything is written.
    if seed_refusals and not dry_run:
        for line in seed_refusals:
            sys.stderr.write(line)
        return 1
    if seed_note:
        print(seed_note)

    # ---- preflight: generated files and orphans, against the overlay -------
    cfg = load_profile(profile_dir)
    outputs = render_staged(cfg, profile_dir, target, seed_plan)
    expected = set(outputs)
    roots = validate_generated_destinations(outputs, target)
    gen_plan, gen_refusals = _plan_generated(target, outputs, force)
    # A malformed inventory raises here, before any delete is even planned.
    inventory = load_inventory(target, roots)
    orphans, orphan_refused = find_orphans(target, expected, inventory)
    if gen_refusals or orphan_refused:
        for line in gen_refusals:
            sys.stderr.write(line)
        for rel in orphan_refused:
            sys.stderr.write(_orphan_refusal(rel))
        return 1
    if inventory is None and is_managed(target, expected):
        sys.stderr.write(
            f"WARNING: {INVENTORY_REL} is missing on an installation this tool already "
            "manages, so orphaned generated files cannot be detected this run; the "
            "inventory is rewritten by this install (check fails until then).\n")

    # ---- dry run -----------------------------------------------------------
    if dry_run:
        for verb, rel, src, _dst in seed_plan:
            if verb != "unchanged":
                print(f"[dry-run] {verb:9s} {rel} ({src.stat().st_size} bytes)")
        if seed_refusals:
            for line in seed_refusals:
                sys.stderr.write(line)
            print(f"[dry-run] this install would be REFUSED: {len(seed_refusals) - 1} seed "
                  "asset(s) differ from the bundle; pass --overwrite-sources to restore the "
                  "bundle's copy, or leave them as the target's own")
            return 1
        for verb, rel in gen_plan:
            print(f"[dry-run] {verb:9s} {rel} ({len(outputs[rel])} bytes)")
        for rel in orphans:
            print(f"[dry-run] remove    {rel} (orphaned generated file)")
        return draft_harness_yaml(target, refresh_env, dry_run)

    # ---- commit: one atomic pass -------------------------------------------
    commit = Commit()
    for verb, rel, src, dst in seed_plan:
        if verb in ("seed", "overwrite"):
            commit.add(dst, src.read_bytes(), src.stat().st_mode & 0o7777)
    if seed_plan and seed_state is not None:
        commit.add(target / SEED_STATE_REL,
                   (json.dumps(seed_state, indent=2, sort_keys=True) + "\n").encode("utf-8"))
    for verb, rel in gen_plan:
        if verb != "unchanged":
            commit.add(target / rel, outputs[rel].encode("utf-8"))
    commit.add(target / INVENTORY_REL,
               (json.dumps(inventory_document(outputs), indent=2, sort_keys=True) + "\n")
               .encode("utf-8"))
    commit.apply()

    for verb, rel, _src, _dst in seed_plan:
        if verb in ("seed", "overwrite"):
            print(f"{verb:9s} {rel}")
    for verb, rel in gen_plan:
        print(f"{verb:9s} {rel}")

    # An orphan is removed only because its bytes still equal what this tool
    # generated (validated in the preflight); anything not in the inventory is
    # never touched. Its key was validated to lie beneath a generated root.
    for rel in orphans:
        (target / rel).unlink()
        print(f"remove    {rel} (orphaned generated file, unchanged since generation)")
        parent = (target / rel).parent
        while parent != target and parent.is_dir() and not any(parent.iterdir()):
            parent.rmdir()
            parent = parent.parent

    # Last: probe this machine and draft harness.yaml, so the SME leaves the
    # install with the detected R/NONMEM/PsN paths in front of them and one
    # thing left to do — confirm them.
    return draft_harness_yaml(target, refresh_env, dry_run)


def cmd_check(target: Path, profile_dir: Path) -> int:
    # check covers the RENDERED files only; seeded assets are a one-time
    # bootstrap and the target legitimately evolves them.
    manifest_path = ADAPTER_DIR / ASSETS_DIRNAME / ASSETS_MANIFEST
    if manifest_path.is_file():
        _warn_self_source(target, json.loads(manifest_path.read_text(encoding="utf-8")))
    cfg = load_profile(profile_dir)
    outputs = render_all(cfg, profile_dir, target)
    expected = set(outputs)
    roots = validate_generated_destinations(outputs, target)
    drift = 0
    for rel, content in outputs.items():
        path = target / rel
        if not path.exists():
            print(f"MISSING  {rel}")
            drift += 1
        elif path.read_text(encoding="utf-8") != content:
            print(f"DRIFT    {rel}")
            sys.stdout.write(_diff(path.read_text(encoding="utf-8"), content, rel))
            drift += 1
        else:
            print(f"OK       {rel}")
    # Orphans: files this generator wrote that the profile no longer expects.
    # Without the inventory `check` iterates only the CURRENT expected map, so a
    # skill, agent or scoped instruction removed from the profile would leave
    # its generated file active and still report green. A malformed inventory
    # raises (exit 2); a MISSING one on a managed installation is a failure.
    inventory = load_inventory(target, roots)
    orphans, orphan_edited = find_orphans(target, expected, inventory)
    for rel in orphans + orphan_edited:
        print(f"ORPHAN   {rel}")
        drift += 1
    if orphans:
        print(f"copilot-adapter check: {len(orphans)} generated file(s) are no longer expected by "
              "the profile — run `setup.py install` to remove them")
    for rel in orphan_edited:
        print(f"copilot-adapter check: {rel} is orphaned AND hand-edited since generation; "
              "`install` will refuse to delete it — review and remove it yourself")
    if inventory is None:
        if is_managed(target, expected):
            print(f"MISSING  {INVENTORY_REL} (this installation is managed — generated files or "
                  "seed state exist — so orphaned generated files cannot be verified; run "
                  "`setup.py install` to rewrite it)")
            drift += 1
        else:
            print(f"note: no {INVENTORY_REL} and nothing generated yet in this target; run "
                  "`setup.py install` to render and write it")
    if drift:
        print(f"copilot-adapter check: {drift} file(s) drift from profile — run `setup.py install --force`")
        return 1
    print(f"copilot-adapter check: {len(outputs)} generated file(s) match the profile")
    return 0


def cmd_init(profile_dir: Path) -> int:
    if profile_dir.exists():
        sys.stderr.write(f"REFUSED: profile already exists at {profile_dir}\n")
        return 1
    shutil.copytree(EXAMPLE_PROFILE, profile_dir)
    print(f"created {profile_dir} from examples/minimal — edit adapter.toml, then run install")
    return 0


def refuse_overlapping_dest(dest: Path, source: Path) -> None:
    """Refuse an export destination that overlaps the source, BEFORE any delete.

    ``export`` replaces ``DEST/copilot-adapter`` with ``shutil.rmtree`` under
    ``--force``. If DEST is the source repository root, the adapter directory
    itself, anything inside either, or any ancestor of them, that delete
    removes the very files being exported. The guard compares resolved paths.
    """
    dest_r = dest.resolve()
    for label, protected in (("the source adapter directory", ADAPTER_DIR),
                             ("the source repository root", source)):
        protected_r = protected.resolve()
        if dest_r == protected_r or _within(dest_r, protected_r) or _within(protected_r, dest_r):
            raise ProfileError(
                f"REFUSED: export destination {dest_r} resolves to, inside, or above "
                f"{label} ({protected_r}). `export` replaces DEST/copilot-adapter and would "
                "delete the files it is exporting. Choose a destination outside the source "
                "repository."
            )


def assert_safe_to_delete(path: Path, source: Path) -> None:
    """Last-line invariant checked immediately before any recursive delete."""
    path_r = path.resolve()
    for label, protected in (("the source adapter directory", ADAPTER_DIR),
                             ("the source repository root", source)):
        protected_r = protected.resolve()
        if path_r == protected_r or _within(protected_r, path_r):
            raise ProfileError(
                f"REFUSED: refusing to delete {path_r}: it is, or contains, {label} "
                f"({protected_r})."
            )


def cmd_export(dest: Path, source: Path, profile_dir: Path,
               force: bool, with_profile: bool) -> int:
    """Copy the generator, the profile, and the payload snapshot to DEST."""
    # First, before any existence check and long before the rmtree below.
    refuse_overlapping_dest(dest, source)
    out = dest / "copilot-adapter"
    if out.exists() and not force:
        sys.stderr.write(f"REFUSED: {out} already exists (use --force to replace it)\n")
        return 1

    generator = [_validate_payload_path(ADAPTER_DIR, rel, require_file=True)
                 for rel in EXPORT_MEMBERS]
    rels: list[str] = []
    empty_optional: list[str] = []
    profile_files: list[str] = []
    stock_modes: dict[str, int] = {}
    workflow_template = TEMPLATES / KIT_WORKFLOW_TMPL
    if with_profile:
        cfg = load_profile(profile_dir)
        exp = cfg.get("export")
        if exp and exp.get("exact") is True:
            rels = exact_payload_paths(source, exp)
            stock_modes = exact_payload_modes(exp)
            profile_files = ["adapter.toml", cfg["project"]["contract"]]
            profile_files.extend(ins["body"] for ins in cfg.get("instructions", []))
            mandate = cfg.get("orchestrator", {}).get("mandate_file")
            if mandate:
                profile_files.append(mandate)
        elif exp:
            patterns = payload_patterns(exp)
            rels, empty = collect_payload(source, [p for p, _ in patterns], exp.get("exclude", []))
            optional = {p for p, is_optional in patterns if is_optional}
            empty_required = [p for p in empty if p not in optional]
            empty_optional = [p for p in empty if p in optional]
            if empty_required:
                # Before any write or delete: a kit missing a required payload
                # group would ship generated files pointing at absent sources.
                raise ProfileError(
                    "REFUSED: required [export].payload pattern(s) matched nothing in "
                    f"{source}: {', '.join(empty_required)}. Fix the pattern, or mark it "
                    '{ path = "...", optional = true } if it may legitimately be absent.')
        refuse_literal_urls(source, rels)

    if out.exists():
        assert_safe_to_delete(out, source)
        shutil.rmtree(out)
    out.mkdir(parents=True)
    for member, src in zip(EXPORT_MEMBERS, generator):
        dst = out / member
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
    if profile_files:
        for rel in sorted(set(profile_files)):
            dst = out / "profile" / rel
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(profile_dir / rel, dst)
    elif with_profile:
        shutil.copytree(profile_dir, out / "profile",
                        ignore=shutil.ignore_patterns("__pycache__"))

    if rels:
        assets_dir = out / ASSETS_DIRNAME
        entries = []
        for rel in rels:
            dst = assets_dir / rel
            dst.parent.mkdir(parents=True, exist_ok=True)
            if rel == KIT_WORKFLOW_REL:
                shutil.copyfile(workflow_template, dst)
                mode = stock_modes.get(rel, stat.S_IMODE((source / rel).stat().st_mode))
                dst.chmod(mode)
            else:
                shutil.copy2(source / rel, dst)
                if rel in stock_modes:
                    dst.chmod(stock_modes[rel])
            file_stat = dst.stat()
            entries.append({"path": rel, "sha256": _sha256(dst),
                            "bytes": file_stat.st_size, "mode": stat.S_IMODE(file_stat.st_mode)})
        manifest = {
            "schema": 1,
            "source_commit": _source_commit(source),
            "exported": datetime.datetime.now(datetime.timezone.utc)
                        .strftime("%Y-%m-%dT%H:%M:%SZ"),
            "assets": entries,
        }
        (assets_dir / ASSETS_MANIFEST).write_text(
            json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
        for pattern in empty_optional:
            sys.stderr.write(f"WARNING: optional [export].payload pattern matched nothing: {pattern}\n")
        print(f"exported {len(entries)} asset(s) + profile to {out} — "
              f"run `python3 {out / 'setup.py'} install` in {dest}")
    else:
        what = "adapter with profile" if with_profile else "adapter (generator only)"
        print(f"exported {what} to {out} — run `python3 {out / 'setup.py'} init` there")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="setup.py", description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)

    def add_common(p: argparse.ArgumentParser, with_profile: bool = True) -> None:
        p.add_argument("--target", type=Path, default=ADAPTER_DIR.parent,
                       help="project root (default: parent of copilot-adapter/)")
        if with_profile:
            p.add_argument("--profile", type=Path, default=None,
                           help="profile directory (default: <target>/copilot-adapter/profile, "
                                "else this adapter's profile/)")

    p_init = sub.add_parser("init", help="create a profile from examples/minimal")
    add_common(p_init, with_profile=False)
    p_install = sub.add_parser("install", help="render the adapter files into the target")
    add_common(p_install)
    p_install.add_argument("--force", action="store_true",
                           help="overwrite differing GENERATED files; never a seed asset")
    p_install.add_argument("--overwrite-sources", action="store_true",
                           help="destroy the target's version of a differing SEED ASSET and "
                                "restore the bundle's copy (can roll back gate machinery and "
                                "approved reference code)")
    p_install.add_argument("--reseed", action="store_true",
                           help="re-enter the seed classification even though "
                                "copilot-adapter/.seed-state.json already records this bundle")
    p_install.add_argument("--dry-run", action="store_true", help="print what would be written")
    p_install.add_argument("--refresh-env", action="store_true",
                           help="re-probe this machine and rewrite the harness.yaml "
                                "environment block (refused once environment_confirmed: true)")
    p_check = sub.add_parser("check", help="exit 1 when live files drift from the profile")
    add_common(p_check)
    p_env = sub.add_parser("env", help="re-probe this machine and report drift against harness.yaml")
    add_common(p_env, with_profile=False)
    p_export = sub.add_parser("export", help="copy the adapter, its profile and the payload to DEST/copilot-adapter")
    p_export.add_argument("dest", type=Path)
    add_common(p_export)
    p_export.add_argument("--no-profile", dest="with_profile", action="store_false",
                          help="generic generator only: no profile, no assets")
    p_export.add_argument("--force", action="store_true",
                          help="replace an existing DEST/copilot-adapter")

    args = parser.parse_args(argv)
    try:
        target = args.target.resolve()
        if args.cmd == "init":
            return cmd_init(target / "copilot-adapter" / "profile")
        if args.cmd == "env":
            return cmd_env(target)
        profile_dir = args.profile
        if profile_dir is None:
            candidate = target / "copilot-adapter" / "profile"
            profile_dir = candidate if candidate.is_dir() else ADAPTER_DIR / "profile"
        profile_dir = profile_dir.resolve()
        if args.cmd == "export":
            return cmd_export(args.dest.resolve(), target, profile_dir,
                              args.force, args.with_profile)
        if args.cmd == "install":
            return cmd_install(target, profile_dir, args.force, args.dry_run,
                               args.refresh_env, args.reseed, args.overwrite_sources)
        return cmd_check(target, profile_dir)
    except ProfileError as err:
        sys.stderr.write(f"ERROR: {err}\n")
        return 2


if __name__ == "__main__":
    sys.exit(main())
