def _glob_re(pattern: str) -> re.Pattern[str]:
    """Translate a repo-relative glob into a regex over posix paths.

    ``**`` crosses directory separators, ``*`` and ``?`` do not. A trailing
    ``/**`` therefore means "every file under this directory".
    """
    out: list[str] = []
    i = 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out.append("(?:[^/]*/)*")
            i += 3
        elif pattern.startswith("**", i):
            out.append(".*")
            i += 2
        elif pattern[i] == "*":
            out.append("[^/]*")
            i += 1
        elif pattern[i] == "?":
            out.append("[^/]")
            i += 1
        else:
            out.append(re.escape(pattern[i]))
            i += 1
    return re.compile("^" + "".join(out) + "$")


def _match_any(rel: str, patterns: list[re.Pattern[str]]) -> bool:
    return any(p.match(rel) for p in patterns)


def _glob_base(pattern: str) -> str:
    """Longest leading directory of a pattern that contains no glob character."""
    parts = pattern.split("/")
    keep: list[str] = []
    for part in parts[:-1]:
        if any(ch in part for ch in "*?["):
            break
        keep.append(part)
    return "/".join(keep)


def _walk_files(root: Path, base_rel: str, excludes: list[re.Pattern[str]]):
    base = root / base_rel if base_rel else root
    if not base.is_dir():
        return
    _validate_payload_path(root, base_rel)
    for dirpath, dirnames, filenames in os.walk(base):
        here = Path(dirpath)
        rel_dir = "" if here == root else here.relative_to(root).as_posix()
        kept_dirs: list[str] = []
        for name in sorted(dirnames):
            rel = f"{rel_dir}/{name}" if rel_dir else name
            if name in SKIP_DIRS:
                continue
            # A directory is pruned when a probe child inside it is excluded,
            # which is what a `dir/**` exclusion means.
            if _match_any(f"{rel}/_", excludes):
                continue
            _validate_payload_path(root, rel)
            kept_dirs.append(name)
        dirnames[:] = kept_dirs
        for name in sorted(filenames):
            rel = f"{rel_dir}/{name}" if rel_dir else name
            if not _match_any(rel, excludes):
                _validate_payload_path(root, rel, require_file=True)
                yield rel


def _validate_payload_path(root: Path, rel: str, require_file: bool = False) -> Path:
    """Validate one export source without following a symlink.

    Payload paths are lexical repository-relative names. Every existing path
    component must be physical (not a symlink), and the resolved member must
    remain beneath the selected source tree. This runs before any payload byte
    is read by URL scanning, hashing, or copying.
    """
    pure = Path(rel)
    if pure.is_absolute() or rel.startswith(("/", "\\")) or ".." in pure.parts:
        raise ProfileError(f"REFUSED: export payload path {rel!r} escapes the source tree")
    current = root
    for part in pure.parts:
        current = current / part
        if current.is_symlink():
            raise ProfileError(
                f"REFUSED: export payload source {rel!r} contains symlink component "
                f"{current}; symlink referents are outside the declared payload boundary")
    if not _within(current, root):
        raise ProfileError(
            f"REFUSED: export payload source {rel!r} resolves outside selected source {root}")
    if require_file and not current.is_file():
        raise ProfileError(f"REFUSED: export payload member {rel!r} is not a regular file")
    return current


def exact_payload_paths(source: Path, exp: dict) -> list[str]:
    modes = exact_payload_modes(exp)
    excludes = [_glob_re(p) for p in exp.get("exclude", [])]
    for rel, mode in modes.items():
        if _match_any(rel, excludes):
            raise ProfileError(f"exact payload file {rel!r} is also excluded")
        path = _validate_payload_path(source, rel, require_file=True)
        source_mode = stat.S_IMODE(path.stat().st_mode)
        if bool(source_mode & stat.S_IXUSR) != bool(mode & stat.S_IXUSR) or source_mode & 0o7000:
            raise ProfileError(f"exact payload file {rel!r} must match the executable class of mode {mode:04o}")
    return sorted(modes)


def collect_payload(root: Path, payload: list[str], exclude: list[str]) -> tuple[list[str], list[str]]:
    """Return (sorted relative paths to export, patterns that matched nothing)."""
    excludes = [_glob_re(p) for p in exclude]
    found: set[str] = set()
    empty: list[str] = []
    for pattern in payload:
        hits: set[str] = set()
        if not any(ch in pattern for ch in "*?["):
            path = root / pattern
            if path.is_symlink():
                _validate_payload_path(root, pattern)
            if path.is_file():
                _validate_payload_path(root, pattern, require_file=True)
                if not _match_any(pattern, excludes):
                    hits.add(pattern)
            elif path.is_dir():
                _validate_payload_path(root, pattern)
                hits.update(_walk_files(root, pattern, excludes))
        else:
            regex = _glob_re(pattern)
            for rel in _walk_files(root, _glob_base(pattern), excludes):
                if regex.match(rel):
                    hits.add(rel)
        if not hits:
            empty.append(pattern)
        found |= hits
    return sorted(found), empty


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 16), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _url_scan_targets(rels: list[str]) -> list[str]:
    scanned = [_glob_re(p) for p in URL_SCAN_PATTERNS]
    return [rel for rel in rels if _match_any(rel, scanned)]


def refuse_literal_urls(root: Path, rels: list[str]) -> None:
    """Refuse the export when a machine-readable config asset carries a URL.

    Scans only the configuration shapes that could hold an MCP endpoint
    (``URL_SCAN_PATTERNS``: any ``*.json``, ``harness*.yaml``, ``config/*.yaml``).
    Prose and code assets may legitimately cite documentation URLs.
    """
    offenders: list[str] = []
    for rel in _url_scan_targets(rels):
        try:
            text = (root / rel).read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        if re.search(r"https?://", text):
            offenders.append(rel)
    if offenders:
        raise ProfileError(
            "REFUSED: literal http(s) endpoint in payload configuration: "
            + ", ".join(offenders)
            + ". MCP endpoints are credentials; use a ${VAR} or ${input:...} placeholder."
        )


def _source_commit(root: Path) -> str:
    try:
        proc = subprocess.run(["git", "-C", str(root), "rev-parse", "HEAD"],
                              capture_output=True, text=True, timeout=10)
    except (OSError, subprocess.SubprocessError):
        return "unknown"
    return proc.stdout.strip() if proc.returncode == 0 and proc.stdout.strip() else "unknown"


def _head_commit(root: Path) -> str:
    return _source_commit(root)


def _warn_self_source(target: Path, manifest: dict) -> None:
    """A bundle installed back onto the tree it was exported from."""
    commit = manifest.get("source_commit", "unknown")
    if commit != "unknown" and commit == _head_commit(target):
        sys.stderr.write(
            f"WARNING: this bundle's assets were exported from the current HEAD ({commit[:12]}); "
            "the live files are their own source — seeding here is a no-op at best.\n"
        )


def _within(child: Path, parent: Path) -> bool:
    """True when ``child`` is ``parent`` or lies beneath it (after resolution)."""
    try:
        child.resolve().relative_to(parent.resolve())
        return True
    except ValueError:
        return False


def validate_asset_paths(entries: list[dict], assets_dir: Path, target: Path,
                         expected: set[str] | None = None) -> None:
    """Refuse a manifest whose paths could write outside the bundle or target.

    Every path must be a non-empty string, unique, repo-relative, free of
    ``..``, and must resolve beneath BOTH the bundle's assets root and the
    target root. This runs in the preflight, before any file is written.
    """
    if not isinstance(entries, list):
        raise ProfileError(f"invalid {ASSETS_MANIFEST}: assets must be a list")
    seen: set[str] = set()
    for entry in entries:
        rel = entry.get("path") if isinstance(entry, dict) else None
        if not isinstance(rel, str) or not rel.strip():
            raise ProfileError(
                f"invalid asset path in {ASSETS_MANIFEST}: {rel!r} is not a non-empty string")
        if rel in seen:
            raise ProfileError(
                f"invalid asset path in {ASSETS_MANIFEST}: duplicate entry {rel!r}")
        seen.add(rel)
        pure = Path(rel)
        if pure.is_absolute() or rel.startswith("/") or rel.startswith("\\"):
            raise ProfileError(
                f"invalid asset path in {ASSETS_MANIFEST}: {rel!r} is absolute; "
                "asset paths are repo-relative")
        if ".." in pure.parts:
            raise ProfileError(
                f"invalid asset path in {ASSETS_MANIFEST}: {rel!r} contains '..'; "
                "asset paths never escape the bundle")
        if pure.as_posix() != rel or rel == "." or "\\" in rel:
            raise ProfileError(f"invalid asset path in {ASSETS_MANIFEST}: {rel!r} is not normalized")
    if expected is not None and seen != expected:
        raise ProfileError(f"{ASSETS_MANIFEST} paths do not match the exact seed profile")
    for rel in sorted(seen):
        for label, root in (("the bundle's assets root", assets_dir),
                            ("the target root", target)):
            try:
                _validate_payload_path(root, rel)
            except ProfileError as exc:
                raise ProfileError(f"invalid asset path in {ASSETS_MANIFEST} ({label}): {exc}") from exc


def read_seed_state(target: Path) -> dict | None:
    path = target / SEED_STATE_REL
    if not path.is_file():
        return None
    try:
        state = json.loads(path.read_text(encoding="utf-8"))
    except ValueError:
        return None
    return state if isinstance(state, dict) else None


def write_seed_state(target: Path, state: dict) -> None:
    _atomic_write_text(target / SEED_STATE_REL,
                       json.dumps(state, indent=2, sort_keys=True) + "\n")


def plan_seed(target: Path, reseed: bool, overwrite_sources: bool
              ) -> tuple[list[tuple[str, str, Path, Path]], list[str], str, dict | None]:
    """Plan the one-time bootstrap of the bundle's payload into the target.

    Returns ``(plan, refusals, note, state)``:

    * ``plan``   -- ``(verb, rel, src, dst)`` tuples; verb is seed / unchanged /
      overwrite. Empty when seeding does not apply or is already recorded.
    * ``refusals`` -- human-readable lines; a non-empty list aborts the install
      before anything is written.
    * ``note``   -- a line to print when seeding was skipped, else "".
    * ``state``  -- the seed-state document to write once the plan is applied.

    Seeding is a ONE-TIME BOOTSTRAP, not synchronisation. It applies only to
    the tree the bundle lives in (``<bundle>/copilot-adapter/..``), and only
    until ``copilot-adapter/.seed-state.json`` records this bundle id. After
    that the target owns its sources outright: ``install`` never looks at the
    assets again unless ``--reseed`` asks it to.

    The three-way classification on (re-)entry is unchanged: a missing
    destination is copied, an identical one is skipped, and a DIFFERING one
    refuses the whole install unless ``--overwrite-sources`` is given.
    ``--force`` has no authority here: it applies to generated outputs only,
    so regenerating Copilot files can never roll back gate machinery or
    approved reference code.
    """
    assets_dir = ADAPTER_DIR / ASSETS_DIRNAME
    # The assets bootstrap the bundle's OWN tree. Rendering into some other
    # --target is a normal generator run and must not seed anything there.
    bundle_root = ADAPTER_DIR.parent
    manifest_path = _validate_payload_path(ADAPTER_DIR, f"{ASSETS_DIRNAME}/{ASSETS_MANIFEST}")
    if not manifest_path.exists():
        return [], [], "", None
    if target.resolve() != bundle_root.resolve():
        return [], [], (f"seeding skipped: this bundle's assets bootstrap {bundle_root}, "
                        f"not --target {target}"), None

    _validate_payload_path(ADAPTER_DIR, f"{ASSETS_DIRNAME}/{ASSETS_MANIFEST}", require_file=True)
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (UnicodeDecodeError, ValueError) as exc:
        raise ProfileError(f"invalid {ASSETS_MANIFEST}: expected a JSON manifest") from exc
    if not isinstance(manifest, dict) or manifest.get("schema") != 1:
        raise ProfileError(f"invalid {ASSETS_MANIFEST}: expected schema 1")
    _warn_self_source(target, manifest)
    entries = manifest.get("assets", [])
    stock_profile = ADAPTER_DIR / "profile"
    modes = None
    if (stock_profile / "adapter.toml").is_file():
        exp = load_profile(stock_profile).get("export", {})
        if exp.get("exact") is True:
            modes = exact_payload_modes(exp)
    validate_asset_paths(entries, assets_dir, target, set(modes) if modes is not None else None)
    if modes is not None:
        for entry in entries:
            if entry.get("mode") != modes[entry["path"]]:
                raise ProfileError(f"asset {entry['path']} does not have its declared mode")

    bundle_id = manifest.get("source_commit", "unknown")
    state = read_seed_state(target)
    if state is not None and not reseed:
        if state.get("bundle_id") == bundle_id:
            return [], [], (
                f"seeding skipped: {SEED_STATE_REL} records bundle "
                f"{str(bundle_id)[:12]} ({len(state.get('assets', {}))} asset(s), seeded "
                f"{state.get('seeded_at', 'unknown')}); pass --reseed to re-enter the "
                "three-way classification"), None
        print(f"bundle id changed ({str(state.get('bundle_id'))[:12]} -> "
              f"{str(bundle_id)[:12]}): re-entering the seed classification")

    plan: list[tuple[str, str, Path, Path]] = []
    conflicts: list[str] = []
    hashes: dict[str, str] = {}
    for entry in entries:
        rel = entry["path"]
        src = assets_dir / rel
        _validate_payload_path(assets_dir, rel, require_file=True)
        mode = entry.get("mode")
        if mode is not None and stat.S_IMODE(src.stat().st_mode) != mode:
            raise ProfileError(f"asset {rel} does not match its recorded mode")
        if "bytes" in entry and src.stat().st_size != entry["bytes"]:
            raise ProfileError(f"asset {rel} does not match its recorded size")
        src_sha = _sha256(src)
        if src_sha != entry["sha256"]:
            raise ProfileError(f"asset {rel} does not match its recorded sha256 — bundle is corrupt")
        hashes[rel] = src_sha
        dst = target / rel
        if not dst.exists():
            plan.append(("seed", rel, src, dst))
        elif not dst.is_file():
            raise ProfileError(f"seed destination {rel} is not a regular file")
        elif _sha256(dst) == src_sha and (mode is None or stat.S_IMODE(dst.stat().st_mode) == mode):
            plan.append(("unchanged", rel, src, dst))
        elif overwrite_sources:
            plan.append(("overwrite", rel, src, dst))
        else:
            conflicts.append(rel)
            # Carried in the plan so --dry-run can SHOW the conflict; the apply
            # path never reaches it, because a non-empty refusal list aborts.
            plan.append(("conflict", rel, src, dst))

    refusals: list[str] = []
    if conflicts:
        refusals.append(
            f"REFUSED: {len(conflicts)} seed asset(s) in the target differ from the bundle's "
            "copy. These are the target's own SOURCES — tools, skills, roles, agents, "
            "pipeline code — and they legitimately evolve after the bootstrap.\n"
            "  --force does NOT apply here: it governs generated Copilot files only.\n"
            "  Pass --overwrite-sources to DESTROY the target's version of each file below "
            "and restore the bundle's copy (this can roll back gate machinery, approved "
            "reference code and signed manifests). Otherwise leave them as the target's own.\n")
        for rel in conflicts:
            refusals.append(f"  {rel}\n")

    state_doc = {
        "schema": 1,
        "bundle_id": bundle_id,
        "seeded_at": datetime.datetime.now(datetime.timezone.utc)
                     .strftime("%Y-%m-%dT%H:%M:%SZ"),
        "assets": hashes,
    }
    return plan, refusals, "", state_doc


# --------------------------------------------------------------------------
# Generated-file inventory (orphan detection)
# --------------------------------------------------------------------------
#
# render_all() knows only the CURRENTLY expected outputs, so a skill, agent or
# scoped instruction removed from the profile would leave its generated file
# active while `check` reported green. The inventory records what this
# generator last wrote, so the managed file SET is verifiable, not just the
# content of the files still expected. It is committed alongside the generated
# files so CI's `check` can use it.

INVENTORY_SCHEMA = 1
SHA256_RE = re.compile(r"^[0-9a-f]{64}$")
# Directories shared with the project (workflows, issue templates live under
# `.github/` too), so a generated root beneath them is one level deeper.
SHARED_DIRS = {".github"}


def _atomic_write_bytes(path: Path, data: bytes) -> None:
    """Write ``data`` to a temporary file beside ``path`` and ``os.replace`` it.

    A reader never sees a half-written file, and a crash mid-write leaves the
    previous content in place.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as fh:
            fh.write(data)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def _atomic_write_text(path: Path, text: str) -> None:
    _atomic_write_bytes(path, text.encode("utf-8"))


def generated_root(rel: str) -> str:
    """The managed root an output path belongs to.

    The first path component, or the first two when the first is a directory
    shared with the project (``.github``): ``.github/agents/x.agent.md`` ->
    ``.github/agents``; ``.github/copilot-instructions.md`` -> itself;
    ``.vscode/mcp.json`` -> ``.vscode``; ``.editorconfig`` -> itself.
    """
    parts = rel.split("/")
    depth = 2 if parts[0] in SHARED_DIRS else 1
    return "/".join(parts[:min(depth, len(parts))])


def generated_roots(expected: set[str]) -> set[str]:
    """Allowed inventory roots, DERIVED from what render_all() produces."""
    return {generated_root(rel) for rel in expected}


def validate_inventory_key(rel: object, target: Path, roots: set[str]) -> str:
    """One inventory path: relative, no ``..``, resolved beneath the target and
    beneath one of the allowed generated roots. Returns the key, or raises."""
    if not isinstance(rel, str) or not rel.strip():
        raise ProfileError(f"invalid {INVENTORY_REL}: key {rel!r} is not a non-empty string")
    pure = Path(rel)
    if pure.is_absolute() or rel.startswith(("/", "\\")) or "\\" in rel:
        raise ProfileError(f"invalid {INVENTORY_REL}: key {rel!r} is absolute; inventory paths are target-relative")
    if ".." in pure.parts or any(part in ("", ".") for part in rel.split("/")):
        raise ProfileError(f"invalid {INVENTORY_REL}: key {rel!r} contains '..' or an empty segment")
    if not _within(target / pure, target):
        raise ProfileError(f"invalid {INVENTORY_REL}: key {rel!r} resolves outside the target {target}")
    root = generated_root(rel)
    if root not in roots:
        raise ProfileError(
            f"invalid {INVENTORY_REL}: key {rel!r} lies outside every generated root "
            f"({', '.join(sorted(roots))}); this tool never manages files there")
    if not _within(target / pure, target / root):
        raise ProfileError(f"invalid {INVENTORY_REL}: key {rel!r} resolves outside its generated root {root}")
    return rel


def validate_generated_destinations(outputs: dict[str, str], target: Path) -> set[str]:
    """Validate every rendered destination before any destination is read.

    Generated paths use the same lexical, target, and managed-root containment
    rules as inventory keys. In addition, no existing path component may be a
    symlink, even when its referent happens to remain inside the target.
    """
    expected = set(outputs)
    roots = generated_roots(expected)
    for rel in sorted(expected):
        pure = Path(rel)
        current = target
        for part in pure.parts:
            current = current / part
            if current.is_symlink():
                raise ProfileError(
                    f"invalid generated destination {rel!r}: path component {current} "
                    "is a symlink; generated writes require physical containment")
        try:
            validate_inventory_key(rel, target, roots)
        except ProfileError as err:
            raise ProfileError(f"invalid generated destination {rel!r}: {err}") from None
    return roots


def load_inventory(target: Path, roots: set[str]) -> dict[str, str] | None:
    """The validated inventory, or ``None`` when the file is absent.

    Anything else that is not a schema-``1`` document with a ``files`` map of
    validated relative path -> lowercase sha256 hex raises ``ProfileError``:
    a malformed inventory is refused, never coerced to ``{}``, because its
    keys are the only paths this tool ever deletes.
    """
    path = target / INVENTORY_REL
    if not path.is_file():
        return None
    try:
        doc = json.loads(path.read_text(encoding="utf-8"))
    except (ValueError, UnicodeDecodeError) as err:
        raise ProfileError(f"invalid {INVENTORY_REL}: not JSON ({err})") from None
    if not isinstance(doc, dict):
        raise ProfileError(f"invalid {INVENTORY_REL}: top level is not an object")
    unknown = set(doc) - {"schema", "generated_at", "files"}
    if unknown:
        raise ProfileError(f"invalid {INVENTORY_REL}: unknown keys {sorted(unknown)}")
    if doc.get("schema") != INVENTORY_SCHEMA:
        raise ProfileError(f"invalid {INVENTORY_REL}: schema must be {INVENTORY_SCHEMA}, got {doc.get('schema')!r}")
    if not isinstance(doc.get("generated_at"), str):
        raise ProfileError(f"invalid {INVENTORY_REL}: generated_at must be a string")
    files = doc.get("files")
    if not isinstance(files, dict):
        raise ProfileError(f"invalid {INVENTORY_REL}: 'files' must be an object of path -> sha256")
    out: dict[str, str] = {}
    for rel, sha in files.items():
        validate_inventory_key(rel, target, roots)
        if not isinstance(sha, str) or not SHA256_RE.match(sha):
            raise ProfileError(f"invalid {INVENTORY_REL}: {rel!r} -> {sha!r} is not a lowercase sha256 hex digest")
        out[rel] = sha
    return out


def inventory_document(outputs: dict[str, str]) -> dict:
    return {
        "schema": INVENTORY_SCHEMA,
        "generated_at": datetime.datetime.now(datetime.timezone.utc)
                        .strftime("%Y-%m-%dT%H:%M:%SZ"),
        "files": {rel: hashlib.sha256(content.encode("utf-8")).hexdigest()
                  for rel, content in sorted(outputs.items())},
    }


def write_inventory(target: Path, outputs: dict[str, str]) -> None:
    _atomic_write_text(target / INVENTORY_REL,
                       json.dumps(inventory_document(outputs), indent=2, sort_keys=True) + "\n")


def is_managed(target: Path, expected: set[str]) -> bool:
    """An installation this tool has already touched: any expected generated
    file exists, or the seed state does."""
    return (target / SEED_STATE_REL).is_file() or any((target / rel).is_file() for rel in expected)


def find_orphans(target: Path, expected: set[str],
                 inventory: dict[str, str] | None) -> tuple[list[str], list[str]]:
    """Split inventory entries that are no longer expected but still exist.

    Returns ``(removable, refused)``. A file is removable only when its bytes
    still equal the hash this generator recorded for it; a hand-edited orphan
    is refused by name and never deleted. Files that were never in the
    inventory are not touched at all — projects own unrelated files under
    `.github/`. ``inventory`` comes from ``load_inventory`` and is therefore
    already validated; ``None`` (absent) yields nothing.
    """
    removable, refused = [], []
    for rel, recorded in sorted((inventory or {}).items()):
        if rel in expected:
            continue
        path = target / rel
        if not path.is_file():
            continue
        if hashlib.sha256(path.read_bytes()).hexdigest() == recorded:
            removable.append(rel)
        else:
            refused.append(rel)
    return removable, refused


# --------------------------------------------------------------------------
# Environment probe and harness.yaml drafting
# --------------------------------------------------------------------------
#
# In a managed environment the engines are already on the user's PATH. The
# harness must not GUESS where they are: `install` probes this machine once,
# writes what it found into harness.yaml with the exact command that found it,
# and leaves `environment_confirmed: false` so nothing runs until the SME has
# read the values. Every probe is a version query with a short timeout; no
# NONMEM, PsN or bbi RUN is ever executed here.

PROBE_TIMEOUT = 6
ENV_BLOCK_BEGIN = "# >>> environment block — generated by copilot-adapter/setup.py"
ENV_BLOCK_END = "# <<< end environment block"
OPS_BLOCK_BEGIN = "# >>> operative settings — generated by copilot-adapter/setup.py"
OPS_BLOCK_END = "# <<< end operative settings"
NMFE_NAMES = ("nmfe75", "nmfe74", "nmfe76")
ENV_CONFIRM_KEY = "environment_confirmed"


def _probe_run(cmd: list[str]) -> tuple[bool, str]:
    """Run one version query. Returns (answered, text). Never raises."""
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True,
                              timeout=PROBE_TIMEOUT)
    except FileNotFoundError:
        return False, "probe failed: executable not found"
    except subprocess.TimeoutExpired:
        return False, f"probe failed: no answer within {PROBE_TIMEOUT}s"
    except OSError as err:
        return False, f"probe failed: {err.strerror or err}"
    # Some tools answer on stderr, some on stdout, a few on both: keep the
    # streams on separate lines so a version string is never spliced.
    out = "\n".join(s.strip() for s in (proc.stdout or "", proc.stderr or "")
                    if s.strip())
    if proc.returncode != 0 and not out:
        return False, f"probe failed: exit {proc.returncode}"
    if proc.returncode != 0:
        return False, "probe failed: " + out.splitlines()[0].strip()
    if not out:
        return False, "probe failed: no output"
    return True, out


def _first_line(text: str) -> str:
    return text.splitlines()[0].strip()


def _engine_image(target: Path) -> str | None:
    """The NONMEM image name from config/engine.yaml, without a YAML parser."""
    path = target / "config" / "engine.yaml"
    if not path.is_file():
        return None
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^\s{4}image:\s*(\S+)", line)
        if m:
            return m.group(1)
    return None


def probe_environment(target: Path) -> dict[str, dict]:
    """Probe this machine's PATH for the harness engines and tooling.

    Returns an ordered mapping key -> {value, command, note, block}. ``value``
    is None when the probe found nothing; ``note`` then says which probe was
    run. ``block`` marks a multi-line value (written as a YAML block scalar).
    """
    found: dict[str, dict] = {}

    def rec(key, value, command, note=None, block=False):
        found[key] = {"value": value, "command": command,
                      "note": note or command, "block": block}

    # --- R ------------------------------------------------------------------
    rscript = shutil.which("Rscript")
    rec("r_rscript", rscript, "shutil.which('Rscript')")
    rbin = shutil.which("R")
    rec("r_binary", rbin, "shutil.which('R')")
    if rscript:
        okv, out = _probe_run([rscript, "--version"])
        rec("r_version", _first_line(out) if okv else None,
            "Rscript --version", None if okv else out)
    else:
        rec("r_version", None, "Rscript --version", "Rscript not on PATH")
    if rbin:
        okv, out = _probe_run([rbin, "RHOME"])
        rec("r_home", _first_line(out) if okv else None,
            "R RHOME", None if okv else out)
    else:
        rec("r_home", None, "R RHOME", "R not on PATH")

    # --- NONMEM -------------------------------------------------------------
    nmfe_probe = "shutil.which(%s)" % ", ".join(repr(n) for n in NMFE_NAMES)
    nmfe = None
    for name in NMFE_NAMES:
        hit = shutil.which(name)
        if hit:
            nmfe = (name, hit)
            break
    rec("nonmem_binary", nmfe[1] if nmfe else None, nmfe_probe)
    # bbi execs <nonmem_home>/run/<nmfe>, so the install root is the parent of
    # the run/ directory the binary sits in.
    home = None
    if nmfe:
        parent = Path(nmfe[1]).resolve().parent
        home = str(parent.parent) if parent.name == "run" else None
    rec("nonmem_home", home,
        "parent of the run/ directory holding the nmfe binary",
        None if nmfe else "no nmfe binary on PATH")
    rec("nonmem_version", nmfe[0] if nmfe else None,
        "nmfe binary name on PATH", None if nmfe else "no nmfe binary on PATH")
    lic = os.environ.get("NONMEM_LICENSE") or None
    rec("nonmem_license", lic, "environment NONMEM_LICENSE")

    # --- PsN ----------------------------------------------------------------
    execute = shutil.which("execute")
    rec("psn_execute", execute, "shutil.which('execute')")
    psn = shutil.which("psn")
    version, cmd, note = None, "execute -version", None
    if execute:
        okv, out = _probe_run([execute, "-version"])
        if okv:
            version, note = _first_line(out), None
        else:
            note = out
    if version is None and psn:
        okv, out = _probe_run([psn, "-version"])
        cmd = "psn -version"
        if okv:
            version, note = _first_line(out), None
        else:
            note = out
    if version is None and note is None:
        note = "no PsN 'execute' or 'psn' on PATH"
    rec("psn_version", version, cmd, note)
    if psn:
        okv, out = _probe_run([psn, "-nm_versions"])
        rec("psn_nm_versions", out if okv else None, "psn -nm_versions",
            None if okv else out, block=True)
    else:
        rec("psn_nm_versions", None, "psn -nm_versions", "psn not on PATH",
            block=True)

    # --- bbi ----------------------------------------------------------------
    bbi = shutil.which("bbi")
    bbi_cmd = "shutil.which('bbi')"
    if not bbi:
        fallback = Path(os.path.expanduser("~/.local/share/bbi/bbi"))
        bbi_cmd = "shutil.which('bbi'), else ~/.local/share/bbi/bbi"
        bbi = str(fallback) if fallback.is_file() else None
    rec("bbi", bbi, bbi_cmd)
    if bbi:
        okv, out = _probe_run([bbi, "version"])
        rec("bbi_version", _first_line(out) if okv else None, "bbi version",
            None if okv else out)
    else:
        rec("bbi_version", None, "bbi version", "bbi not found")

    # --- reporting and container tooling ------------------------------------
    for key, exe, argv in (("quarto_version", "quarto", ["--version"]),
                           ("tectonic_version", "tectonic", ["--version"]),
                           ("docker_version", "docker", ["--version"])):
        path = shutil.which(exe)
        cmdline = f"{exe} {' '.join(argv)}"
        if not path:
            rec(key, None, cmdline, f"{exe} not on PATH")
            continue
        okv, out = _probe_run([path] + argv)
        rec(key, _first_line(out) if okv else None, cmdline,
            None if okv else out)

    image = _engine_image(target)
    docker = shutil.which("docker")
    if image is None:
        rec("nonmem_image", None, "config/engine.yaml engines.nonmem.image",
            "no image named in config/engine.yaml")
    elif not docker:
        rec("nonmem_image", None, f"docker images -q {image}",
            "docker not on PATH")
    else:
        okv, out = _probe_run([docker, "images", "-q", image])
        rec("nonmem_image", image if (okv and out) else None,
            f"docker images -q {image}",
            None if (okv and out) else f"image not built locally: {image}")

    return found


def _yaml_scalar(value: str) -> str:
    """Quote only when a plain scalar would not round-trip."""
    if value == "" or value != value.strip():
        return json.dumps(value)
    if re.search(r':\s|\s#|^[\[\]{}>|*&!%@`\"\'-]|[:#]$', value):
        return json.dumps(value)
    return value


def _provision_suggestion(probe: dict) -> tuple[str | None, str]:
    """native, containerized, or undecided — with the reason either way."""
    nm = probe["nonmem_binary"]
    if nm["value"]:
        return "native", f"{nm['value']} found via {nm['command']}"
    img, docker = probe["nonmem_image"], probe["docker_version"]
    if docker["value"] and img["value"]:
        return "containerized", f"{img['command']} answered"
    return None, f"{nm['note']}; {docker['note']}; {img['note']}"


def render_operative_block(probe: dict, now: str) -> str:
    """The keys the harness READS, pre-filled from the probe.

    Distinct from the environment block below it: that block is a report,
    this one is configuration. Every value carries the command that found
    it, and nothing is written for a tool the probe did not find — the key
    is commented out with the reason instead, so the SME sees the gap
    rather than a guess.

    The licence is a credential: only the PATH is recorded, only when the
    SME already set NONMEM_LICENSE. The file is never opened, never
    searched for and never copied.
    """
    home, lic = probe["nonmem_home"], probe["nonmem_license"]
    lines = [
        OPS_BLOCK_BEGIN,
        "# Operative settings — pre-filled from the probe, review and confirm.",
        "# These are the keys the harness READS. The environment: block at the",
        "# bottom of this file is the full probe REPORT, not configuration.",
        "",
        "# --- R provision ---",
        "# managed: development machine; setup_environment.R may install packages",
        "#          from the pinned MPN snapshot.",
        "# site:    regulated environment; the validated system R library is",
        "#          authoritative. setup_environment.R refuses to run and the",
        "#          environment check verifies packages against",
        "#          config/r-packages.lock instead (mismatches reported, never",
        "#          auto-fixed).",
        "# The probe cannot tell these apart — this is a decision, not a fact",
        "# about the machine. Change it to `site` in a regulated environment.",
        "r_provision: managed",
        "",
        "# --- NONMEM/PsN, native provision ---",
        "# Site NONMEM install root; bbi executes <nonmem_home>/run/nmfe75.",
        "# Only the bbr lane needs this (PsN finds NONMEM via its own psn.conf).",
    ]
    if home["value"]:
        lines.append(f"nonmem_home: {_yaml_scalar(home['value'])}   "
                     f"# detected {now} via {home['command']}")
    else:
        lines.append(f"# nonmem_home:   # not found: {home['note']}")
    lines += [
        "",
        "# Optional env file the dispatcher sources before native execution, so",
        "# batch / non-login contexts receive the site PATH (e.g. a profile.d",
        "# snippet or module-load wrapper). Site-provided: the probe never",
        "# guesses it.",
        "# nonmem_env_file: /etc/profile.d/nonmem.sh",
        "",
        "# --- NONMEM license (a PATH only; the file itself is a credential) ---",
        "# Resolved as NONMEM_LICENSE (environment), else the key below, else the",
        "# run is refused with \"NONMEM license not configured\". No path is ever",
        "# invented: the probe records this key only when NONMEM_LICENSE is",
        "# already set, and never reads or copies the file.",
    ]
    if lic["value"]:
        lines.append(f"nonmem_license: {_yaml_scalar(lic['value'])}   "
                     f"# detected {now} via {lic['command']}")
    else:
        lines.append("# nonmem_license:   # not found: NONMEM_LICENSE is not set "
                     "in this environment")
    lines += _container_notes(probe, now)
    lines.append(OPS_BLOCK_END)
    return "\n".join(lines) + "\n"


def _container_notes(probe: dict, now: str) -> list[str]:
    """Document the local image setting and environment-only extra mounts.

    Confirm the locally supplied image with the other operative settings.
    The launcher reads NONMEM_EXTRA_MOUNTS from the environment.
    """
    suggestion, reason = _provision_suggestion(probe)
    img = probe["nonmem_image"]
    docker = probe["docker_version"]
    lines = ["", "# --- NONMEM/PsN, containerized provision ---"]
    if docker["value"]:
        lines += [
            "# Local container image, resolved as NONMEM_IMAGE (environment),",
            "# then the key below. The site operator supplies the licensed image.",
        ]
        if img["value"]:
            lines.append(f"nonmem_image: {_yaml_scalar(img['value'])}   "
                         f"# detected {now} via {img['command']}")
        else:
            lines.append(f"# nonmem_image:   # not found: {img['note']}")
        lines += [
            "# Extra read-only mounts stay an environment variable: export",
            "# NONMEM_EXTRA_MOUNTS as a colon-separated path list before running.",
        ]
    if suggestion == "containerized":
        lines.append(f"# This machine looks containerized ({reason}).")
    elif suggestion == "native":
        lines.append(f"# Not needed: this machine looks native ({reason}).")
    else:
        lines.append(f"# Not suggested for this machine: {reason}")
    return lines


def render_environment_block(probe: dict, now: str) -> str:
    lines = [
        ENV_BLOCK_BEGIN,
        "# Probed on THIS machine by `setup.py install` / `setup.py env`.",
        "# Review every value, correct what is wrong, then set",
        f"# {ENV_CONFIRM_KEY}: true at the top of this file. Nothing runs",
        "# before that: tools/check_environment.R is the enforcement.",
        "environment:",
    ]
    for key, item in probe.items():
        provenance = f"# detected {now} via {item['command']}"
        if item["value"] is None:
            lines.append(f"  # {key}:   # not found: {item['note']}")
        elif item["block"]:
            lines.append(f"  {provenance}")
            lines.append(f"  {key}: |-")
            lines.extend(f"    {ln}" for ln in item["value"].splitlines())
        else:
            lines.append(f"  {key}: {_yaml_scalar(item['value'])}   {provenance}")
    suggestion, reason = _provision_suggestion(probe)
    lines.append("")
    lines.append("# Suggested config/engine.yaml engines.nonmem.provision for this machine.")
    if suggestion:
        lines.append(f"nonmem_provision_suggested: {suggestion}   "
                     f"# detected {now} via {reason}")
    else:
        lines.append(f"# nonmem_provision_suggested:   # not found: {reason}")
    lines.append(ENV_BLOCK_END)
    return "\n".join(lines) + "\n"


def _confirmed(text: str) -> bool:
    """Parse the top-level confirmation as a strict YAML 1.1 boolean subset.

    The portable adapter intentionally has no Python YAML dependency. This
    parser therefore accepts only the ordinary block-mapping form emitted by
    the adapter, including an inline comment, and matches yaml::read_yaml's
    YAML 1.1 boolean spellings. The confirmation value must be an unquoted
    boolean; tagged, anchored, aliased, or malformed confirmation values and
    unsupported root/key forms or duplicate top-level keys are refused.
    Nested content under other keys is not interpreted by this confirmation
    check. Unsupported confirmation forms must never be silently classified
    as unconfirmed and rewritten.
    """
    matches: list[tuple[int, str]] = []
    top_keys: dict[str, int] = {}
    saw_top_mapping = False
    for lineno, line in enumerate(text.splitlines(), 1):
        if "\x00" in line:
            raise ProfileError("invalid harness.yaml: NUL byte is not valid YAML text")
        stripped = line.lstrip()
        if not stripped or stripped.startswith("#"):
            continue
        if line[0].isspace():
            if line.startswith("\t"):
                raise ProfileError(
                    f"invalid harness.yaml line {lineno}: tab indentation is not supported")
            if not saw_top_mapping:
                raise ProfileError(
                    f"invalid harness.yaml line {lineno}: indented content appears before "
                    "a top-level mapping key")
            continue
        # Only the plain top-level block mapping emitted by this adapter is
        # accepted. This rejects flow documents, quoted/escaped keys, explicit
        # keys, document tags, anchors/merge keys, and malformed root scalars
        # even when they conceal the literal confirmation-key spelling.
        code = re.split(r"[ \t]+#", line, maxsplit=1)[0]
        top = re.match(r"^([A-Za-z_][A-Za-z0-9_-]*):(?:[ \t]+(.*)|[ \t]*)$", code)
        if not top:
            raise ProfileError(
                f"invalid harness.yaml line {lineno}: only plain top-level block mapping "
                "keys are supported; flow, quoted, explicit, tagged, anchored, merged, "
                "or malformed root forms are refused")
        saw_top_mapping = True
        key, raw = top.group(1), top.group(2) or ""
        if key in top_keys:
            raise ProfileError(
                f"invalid harness.yaml: duplicate top-level key {key!r} on lines "
                f"{top_keys[key]} and {lineno}")
        top_keys[key] = lineno
        if key == ENV_CONFIRM_KEY:
            matches.append((lineno, raw))
    if not matches:
        return False
    lineno, raw = matches[0]
    scalar = raw.strip()
    value = scalar.lower()
    if value in {"true", "yes", "on", "y"}:
        return True
    if value in {"false", "no", "off", "n"}:
        return False
    raise ProfileError(
        f"invalid harness.yaml line {lineno}: {ENV_CONFIRM_KEY} must be an unquoted "
        "YAML boolean (true/false, yes/no, on/off, or y/n); "
        f"got {scalar!r}")


def _replace_block(text: str, begin: str, end_marker: str, block: str,
                   append_when_absent: bool) -> str:
    """Rewrite a delimited block in place.

    ``append_when_absent`` is the difference between the two blocks on a
    hand-written harness.yaml: the environment REPORT may be appended to a
    file that has never seen it, but the operative section may not — those
    keys are the user's own, and a marker-less file is by definition one the
    user wrote themselves.
    """
    start_match = re.search(rf"^{re.escape(begin)}[ \t]*$", text, re.MULTILINE)
    end_match = re.search(rf"^{re.escape(end_marker)}[ \t]*$", text, re.MULTILINE)
    if (start_match is None) != (end_match is None):
        raise ProfileError(
            f"invalid harness.yaml: generated block has only one marker from "
            f"{begin!r} / {end_marker!r}")
    if start_match is None:
        if not append_when_absent:
            return text
        return text.rstrip("\n") + "\n\n" + block
    assert end_match is not None
    if end_match.start() < start_match.end():
        raise ProfileError(
            f"invalid harness.yaml: generated block end marker {end_marker!r} "
            "appears before its begin marker")
    return text[:start_match.start()] + block + text[end_match.end():].lstrip("\n")


def _replace_env_block(text: str, block: str) -> str:
    return _replace_block(text, ENV_BLOCK_BEGIN, ENV_BLOCK_END, block,
                          append_when_absent=True)


def _replace_ops_block(text: str, block: str) -> str:
    return _replace_block(text, OPS_BLOCK_BEGIN, OPS_BLOCK_END, block,
                          append_when_absent=False)


def _draft_header(now: str) -> str:
    return (
        "# harness.yaml — MACHINE-LOCAL settings, drafted by\n"
        f"# copilot-adapter/setup.py on {now}. This file is git-ignored and\n"
        "# never committed.\n"
        "#\n"
        "# The operative settings below are pre-filled from the probe: they\n"
        "# are what the harness READS. The environment block at the bottom is\n"
        "# the full probe report. READ BOTH, correct anything wrong, then set\n"
        "# the flag below to true. No pipeline runs until you do.\n"
        f"{ENV_CONFIRM_KEY}: false\n"
    )


def _print_probe_table(probe: dict, out=None) -> None:
    out = out or sys.stdout
    out.write("\nEnvironment probe (this machine's PATH):\n")
    width = max(len(k) for k in probe)
    for key, item in probe.items():
        if item["value"] is None:
            shown = f"not found ({item['note']})"
        elif item["block"]:
            shown = item["value"].splitlines()[0] + (
                " …" if len(item["value"].splitlines()) > 1 else "")
        else:
            shown = item["value"]
        out.write(f"  {key.ljust(width)}  {shown}\n")


def draft_harness_yaml(target: Path, refresh: bool, dry_run: bool) -> int:
    """Draft (or refresh) the target's harness.yaml.

    A draft carries two generated sections: the operative settings the
    harness reads (pre-filled from the probe) and the environment report.
    With ``refresh`` both are re-probed — but only where this generator's
    markers already are. An EXISTING harness.yaml with no markers is a
    hand-written file: its operative keys are never touched, only the
    environment report is appended. Either way the rewrite is refused once
    ``environment_confirmed: true``, so a confirmed value is never silently
    replaced by a re-probe.
    """
    now = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    probe = probe_environment(target)
    block = render_environment_block(probe, now)
    ops = render_operative_block(probe, now)
    path = target / "harness.yaml"

    if path.exists():
        if not refresh:
            print("unchanged harness.yaml (exists; --refresh-env re-probes the "
                  "environment block)")
            _print_probe_table(probe)
            return 0
        text = path.read_text(encoding="utf-8")
        if _confirmed(text):
            sys.stderr.write(
                f"REFUSED: harness.yaml carries {ENV_CONFIRM_KEY}: true — the "
                "environment is confirmed and will not be re-probed.\n"
                f"Set {ENV_CONFIRM_KEY}: false first if this machine really "
                "changed, then run install --refresh-env again.\n")
            return 1
        # The operative section is rewritten only where the generator put it.
        # A marker-less file is hand-written: its keys are left alone and only
        # the environment report is appended.
        updated = _replace_ops_block(_replace_env_block(text, block), ops)
        if dry_run:
            print(f"[dry-run] refresh   harness.yaml ({len(updated)} bytes)")
        else:
            path.write_text(updated, encoding="utf-8")
            print("refresh   harness.yaml (environment block re-probed)")
        _print_probe_table(probe)
        _print_review_instruction()
        return 0

    example = target / "harness.yaml.example"
    body = example.read_text(encoding="utf-8") if example.is_file() else ""
    # The example carries `r_provision: managed` as live YAML; the operative
    # section now owns that key, so the example's copy is commented out to
    # keep the drafted file free of duplicate keys.
    body = re.sub(r"^r_provision:(.*)$",
                  r"# r_provision:\1   # set in the operative settings above",
                  body, flags=re.MULTILINE)
    content = (_draft_header(now) + "\n" + ops + "\n"
               + body.rstrip("\n") + "\n\n" + block)
    if dry_run:
        print(f"[dry-run] draft     harness.yaml ({len(content)} bytes)")
    else:
        path.write_text(content, encoding="utf-8")
        print("wrote     harness.yaml (draft — review and confirm)")
    _print_probe_table(probe)
    _print_review_instruction()
    return 0


def _print_review_instruction() -> None:
    print(
        "\nReview harness.yaml: correct any path or version above, then set\n"
        f"  {ENV_CONFIRM_KEY}: true\n"
        "at the top of the file. tools/check_environment.R refuses to run any\n"
        "pipeline until that flag is true, so nothing executes against an\n"
        "unreviewed environment. Re-probe later with\n"
        "  python3 copilot-adapter/setup.py env\n")


def parse_environment_block(text: str) -> dict[str, str] | None:
    """Read the `environment:` mapping out of a harness.yaml, or None."""
    lines = text.splitlines()
    try:
        start = next(i for i, ln in enumerate(lines)
                     if re.match(r"^environment:\s*(#.*)?$", ln))
    except StopIteration:
        return None
    values: dict[str, str] = {}
    i = start + 1
    while i < len(lines):
        line = lines[i]
        if line.strip() == "" or line.lstrip().startswith("#"):
            if line.strip() and not line.startswith(" "):
                break
            i += 1
            continue
        if not line.startswith("  "):
            break
        m = re.match(r"^  ([A-Za-z_][A-Za-z0-9_]*):\s*(.*)$", line)
        if not m:
            i += 1
            continue
        key, raw = m.group(1), m.group(2)
        if raw.startswith("|"):
            i += 1
            body = []
            while i < len(lines) and (lines[i].startswith("    ") or not lines[i].strip()):
                if lines[i].strip():
                    body.append(lines[i][4:])
                i += 1
            values[key] = "\n".join(body)
            continue
        values[key] = _strip_comment(raw)
        i += 1
    return values


def _strip_comment(raw: str) -> str:
    raw = raw.strip()
    if raw.startswith('"'):
        try:
            decoded, idx = json.JSONDecoder().raw_decode(raw)
            return decoded
        except ValueError:
            pass
    cut = re.split(r"\s+#", raw, maxsplit=1)[0]
    return cut.strip()


OPERATIVE_KEYS = ("nonmem_home", "nonmem_license", "nonmem_image")


def parse_operative_keys(text: str) -> dict[str, str]:
    """Top-level operative keys as live YAML (commented-out keys are absent)."""
    values: dict[str, str] = {}
    for key in OPERATIVE_KEYS:
        m = re.search(rf"^{key}:[ \t]*(.*)$", text, re.MULTILINE)
        if m:
            values[key] = _strip_comment(m.group(1))
    return values


def _operative_drift(probe: dict, text: str) -> list[str]:
    """Compare the probe against the keys the harness actually reads."""
    recorded = parse_operative_keys(text)
    out = []
    for key in OPERATIVE_KEYS:
        was, now = recorded.get(key), probe[key]["value"]
        if was is None and now is None:
            continue
        if was is None:
            out.append(f"  drift  operative {key}: not set in harness.yaml, "
                       f"probe found {now!r}")
        elif now is None:
            out.append(f"  drift  operative {key}: harness.yaml has {was!r}, "
                       f"probe found nothing ({probe[key]['note']})")
        elif was != now:
            out.append(f"  drift  operative {key}: harness.yaml has {was!r}, "
                       f"probe found {now!r}")
    return out


def cmd_env(target: Path) -> int:
    """Re-probe and report drift against the target's harness.yaml."""
    probe = probe_environment(target)
    _print_probe_table(probe)
    path = target / "harness.yaml"
    if not path.is_file():
        print(f"\nharness.yaml not found in {target}: run "
              "`python3 copilot-adapter/setup.py install` to draft it from the "
              "probe above, then review and confirm it.")
        return 0
    text = path.read_text(encoding="utf-8")
    operative = _operative_drift(probe, text)
    recorded = parse_environment_block(text)
    if recorded is None:
        if operative:
            print("\nOPERATIVE DRIFT — harness.yaml no longer matches this machine:")
            for line in operative:
                print(line)
        print("\nharness.yaml carries no `environment:` block: run "
              "`python3 copilot-adapter/setup.py install --refresh-env` to add "
              "one from the probe above.")
        return 1 if operative else 0
    drifted = list(operative)
    for key, item in probe.items():
        was = recorded.get(key)
        now = item["value"]
        if was is None and now is None:
            continue
        if was is None:
            drifted.append(f"  drift  {key}: not recorded, probe found {now!r}")
        elif now is None:
            drifted.append(f"  drift  {key}: harness.yaml has {was!r}, "
                           f"probe found nothing ({item['note']})")
        elif was != now:
            drifted.append(f"  drift  {key}: harness.yaml has {was!r}, "
                           f"probe found {now!r}")
    for key in sorted(set(recorded) - set(probe)):
        drifted.append(f"  drift  {key}: recorded but not probed by this version")
    if not drifted:
        print("\nNo drift: harness.yaml matches this machine.")
        return 0
    print(f"\nENVIRONMENT DRIFT ({len(drifted)}) — harness.yaml no longer "
          "describes this machine:")
    for line in drifted:
        print(line)
    print("\nCorrect harness.yaml by hand, or set "
          f"{ENV_CONFIRM_KEY}: false and run "
          "`python3 copilot-adapter/setup.py install --refresh-env`, then "
          "review and confirm again.")
    return 1


