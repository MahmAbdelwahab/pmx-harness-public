#!/usr/bin/env python3
"""copilot-adapter/setup.py — generate a project's GitHub Copilot adapter.

Renders, from a per-project profile (``adapter.toml`` plus markdown fragments):

  .github/copilot-instructions.md            auto-loaded operating contract
  .github/instructions/<slug>.instructions.md path-scoped rules (applyTo glob)
  .github/hooks/<file>.json                  PreToolUse write guard + SessionStart
                                             mandate (Copilot native hook format)
  .github/agents/<name>.agent.md             custom agents rendered from the Claude
                                             agent files (model + tool mapping)
  .github/agents/<orchestrator>.agent.md     orchestrator agent: role spec + dispatch map
  .github/skills/<name>/SKILL.md             skill shims pointing at skills/<name>/SKILL.md
  .vscode/mcp.json                           MCP servers via ${input:...} only
  .vscode/settings.json                      markdown byte-exact protection +
                                             terminal autoApprove barrier +
                                             agent-discovery locations
  .editorconfig                              markdown byte-exact protection

The agents, skills and hooks sources are optional; a profile without them
renders the five v1 files only. Rendering the agents and skills sources reads
the TARGET tree (``.claude/agents``, ``skills/``, ``roles/``, the dispatch-map
document) so those files stay the single source of truth.

Commands:
  init    [--target DIR]                          create <target>/copilot-adapter/profile from examples/minimal
  install [--target DIR] [--profile DIR] [--force] [--dry-run] [--refresh-env]
          [--reseed] [--overwrite-sources]
                                                  seed the payload ONCE (recorded in
                                                  copilot-adapter/.seed-state.json), render,
                                                  record copilot-adapter/.generated-inventory.json,
                                                  then probe this machine and draft
                                                  harness.yaml (environment_confirmed: false)
  env     [--target DIR]                          re-probe and report drift against harness.yaml
  check   [--target DIR] [--profile DIR]          exit 1 with diffs when live files drift
  export  DEST [--target DIR] [--profile DIR] [--no-profile] [--force]
                                                  copy the generator, the profile and the
                                                  payload snapshot to DEST/copilot-adapter

Requires python3 >= 3.11 (tomllib); standard library only. No third-party
templating: ``{{key}}`` substitution plus verbatim fragment inclusion.

Two bookkeeping files are written into the TARGET by ``install``, and both are
committed alongside the generated files (``.gitignore`` must not exclude them):

  copilot-adapter/.seed-state.json          bundle id + UTC time + per-asset
                                            hashes; makes seeding one-time
  copilot-adapter/.generated-inventory.json path -> sha256 of what was
                                            generated; lets ``check`` detect a
                                            generated file the profile no
                                            longer expects

Security invariants:

* An ``[[mcp]]`` entry that carries a literal ``url`` key is REFUSED. MCP
  endpoint URLs are credentials in the projects this adapter serves; the only
  URL ever written is ``${input:<id>-url}``.
* ``export`` refuses a destination that resolves to, inside, or above the
  source adapter directory or the source repository root, and asserts the same
  invariant again immediately before the ``rmtree``.
* Every ``ASSETS.json`` path is validated (unique, relative, no ``..``,
  contained beneath both the bundle root and the target root) before any write.
* ``--force`` governs generated outputs only; seed assets need the separate,
  explicit ``--overwrite-sources``.
"""

