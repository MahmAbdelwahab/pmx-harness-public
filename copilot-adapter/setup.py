def _hook_entry(command: str, timeout: int) -> dict:
    """One hook command entry with the command under both `command` and `bash`."""
    return {"type": "command", "command": command, "bash": command, "timeoutSec": timeout}


def render_hooks(cfg: dict) -> str:
    """Copilot native hook file (.github/hooks/<file>.json). VS Code reads the
    same file (it converts the lowerCamelCase event names and maps `bash` to
    linux/osx); the Copilot cloud agent reads only this location and honours
    only `bash`. Each entry carries the command under BOTH keys: `bash` for the
    cloud agent, and the cross-platform `command` because VS Code resolves the
    platform-specific key against the workbench (client) OS -- in a Remote-SSH
    session from a Windows client a bash-only entry showed as "(unset)" in the
    Hooks view (observed 2026-09-02). The command is repo-relative: both
    runtimes run hooks with cwd = workspace root, and none of them sets
    $CLAUDE_PROJECT_DIR. Plain JSON: no marker line possible."""
    hooks = cfg["hooks"]
    timeout = int(hooks.get("timeout_sec", 10))
    events: dict[str, list] = {}
    if hooks.get("pre_tool_use"):
        events["preToolUse"] = [_hook_entry(hooks["pre_tool_use"], timeout)]
    if hooks.get("session_start"):
        events["sessionStart"] = [_hook_entry(hooks["session_start"], timeout)]
    return json.dumps({"version": 1, "hooks": events}, indent=2, ensure_ascii=False) + "\n"


def _yaml_str(text: str) -> str:
    """A double-quoted YAML scalar (JSON string syntax is valid YAML)."""
    return json.dumps(text, ensure_ascii=False)


def _yaml_list(items: list[str]) -> str:
    return "[" + ", ".join("'" + i.replace("'", "''") + "'" for i in items) + "]"


def parse_agent_file(path: Path) -> dict:
    """Parse a Claude Code agent definition: `---` frontmatter of simple
    `key: value` lines, then the body. Returns name/description/model/tools/body."""
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        raise ProfileError(f"{path}: no YAML frontmatter")
    end = text.find("\n---\n", 4)
    if end < 0:
        raise ProfileError(f"{path}: unterminated frontmatter")
    header, body = text[4:end], text[end + len("\n---\n"):]
    fields: dict[str, str] = {}
    for line in header.splitlines():
        if not line.strip():
            continue
        if ":" not in line:
            raise ProfileError(f"{path}: cannot parse frontmatter line {line!r}")
        key, _, value = line.partition(":")
        fields[key.strip()] = value.strip()
    unknown = set(fields) - AGENT_FRONTMATTER_KEYS
    if unknown:
        raise ProfileError(f"{path}: unsupported frontmatter keys {sorted(unknown)}")
    name = fields.get("name") or path.stem
    if name != path.stem:
        raise ProfileError(f"{path}: frontmatter name '{name}' differs from file stem '{path.stem}'")
    tools = [t.strip() for t in fields.get("tools", "").split(",") if t.strip()]
    return {
        "name": name,
        "description": fields.get("description", ""),
        "model": fields.get("model", ""),
        "tools": tools,
        "body": body,
        "source": path,
    }


def _map_tools(agent: dict, mapping: dict) -> list[str]:
    out: list[str] = []
    for tool in agent["tools"]:
        if tool not in mapping:
            raise ProfileError(
                f"agent '{agent['name']}' ({agent['source']}): tool '{tool}' has no entry in "
                "[agents.tools]; add the mapping (VS Code would silently drop it)"
            )
        mapped = mapping[tool]
        if mapped not in out:
            out.append(mapped)
    return out


def _map_model(agent_name: str, model: str, models: dict) -> list[str]:
    if not model or model == "inherit":
        return []
    if model not in models:
        raise ProfileError(
            f"agent '{agent_name}': model '{model}' has no entry in [agents.models]; the "
            "adapter never falls back to a weaker model — add the display name"
        )
    return [models[model]]


def _frontmatter(lines: list[str]) -> str:
    return "---\n" + "\n".join(lines) + "\n---\n"


def render_agent(agent: dict, cfg: dict, target: Path) -> str:
    acfg = cfg["agents"]
    rel_source = agent["source"].resolve().relative_to(target.resolve()).as_posix()
    lines = [f"name: {agent['name']}", f"description: {_yaml_str(agent['description'])}"]
    model = _map_model(agent["name"], agent["model"], acfg["models"])
    if model:
        lines.append(f"model: {_yaml_list(model)}")
    lines.append(f"tools: {_yaml_list(_map_tools(agent, acfg['tools']))}")
    if agent["name"] in acfg.get("disable_model_invocation", []):
        lines.append("disable-model-invocation: true")
    # Every specialist carries an explicit empty `agents` list. VS Code's
    # `validateSubagentAllowed` consults only the CALLING agent's `agents` list;
    # `disable-model-invocation` merely hides an agent from the model-visible
    # list and does not stop a call. An empty list is therefore what actually
    # makes "the reviewer is reachable only through the orchestrator" true, and
    # it keeps specialists from dispatching each other.
    lines.append("agents: []")
    generated = (
        f"This agent definition is generated from `{rel_source}` by copilot-adapter/setup.py; "
        "edit that file, then run install. The body below is the Claude agent body verbatim. "
        "The empty `agents` list is deliberate: subagent dispatch is the orchestrator's "
        "job, and an explicit empty list is the only enforced way to say so."
    )
    return _frontmatter(lines) + f"<!-- {MARKER_TEXT} -->\n{generated}\n\n" + agent["body"].lstrip("\n")


def _extract_section(text: str, heading: str, where: str) -> str:
    """Return the markdown section starting at the line that begins with
    `heading` up to (not including) the next heading of the same level."""
    lines = text.splitlines(keepends=True)
    level = len(heading) - len(heading.lstrip("#"))
    start = next((i for i, ln in enumerate(lines) if ln.startswith(heading)), None)
    if start is None:
        raise ProfileError(f"{where}: heading {heading!r} not found")
    end = len(lines)
    for j in range(start + 1, len(lines)):
        if lines[j].startswith("#" * level + " "):
            end = j
            break
    return "".join(lines[start:end]).rstrip("\n") + "\n"


def render_orchestrator(cfg: dict, target: Path, specialist_names: list[str]) -> str:
    acfg = cfg["agents"]
    orch = acfg["orchestrator"]
    role_path = target / orch["role_file"]
    if not role_path.is_file():
        raise ProfileError(f"[agents.orchestrator].role_file not found: {role_path}")
    lines = [f"name: {orch['name']}", f"description: {_yaml_str(orch['description'])}"]
    model = _map_model(orch["name"], orch.get("model", ""), acfg["models"])
    if model:
        lines.append(f"model: {_yaml_list(model)}")
    lines.append(f"tools: {_yaml_list(list(orch['tools']))}")
    lines.append(f"agents: {_yaml_list(specialist_names)}")
    lines.append("user-invocable: true")
    body = role_path.read_text(encoding="utf-8").rstrip("\n") + "\n"
