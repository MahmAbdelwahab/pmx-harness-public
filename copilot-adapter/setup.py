def render_agents(cfg: dict, target: Path) -> dict[str, str]:
    acfg = cfg["agents"]
    src_dir = target / acfg["source_dir"]
    if not src_dir.is_dir():
        raise ProfileError(f"[agents].source_dir not found: {src_dir}")
    pattern = acfg.get("glob", "*.md")
    files = sorted(p for p in src_dir.glob(pattern) if p.is_file())
    if not files:
        raise ProfileError(f"[agents]: no files match {pattern!r} in {src_dir}")
    agents = [parse_agent_file(p) for p in files]
    out: dict[str, str] = {}
    for agent in agents:
        out[f".github/agents/{agent['name']}.agent.md"] = render_agent(agent, cfg, target)
    orch = acfg.get("orchestrator")
    if orch:
        if orch["name"] in {a["name"] for a in agents}:
            raise ProfileError(f"[agents.orchestrator].name '{orch['name']}' collides with a specialist agent")
        out[f".github/agents/{orch['name']}.agent.md"] = render_orchestrator(
            cfg, target, [a["name"] for a in agents]
        )
    return out


