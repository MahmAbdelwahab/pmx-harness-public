class ProfileError(Exception):
    """A profile that must not be rendered."""


# --------------------------------------------------------------------------
# Profile loading and validation
# --------------------------------------------------------------------------

def load_profile(profile_dir: Path) -> dict:
    toml_path = _validate_payload_path(profile_dir.resolve(), "adapter.toml", require_file=True)
    with toml_path.open("rb") as fh:
        cfg = tomllib.load(fh)
    validate(cfg, profile_dir)
    return cfg


def _require(table: dict, key: str, where: str) -> object:
    if key not in table or table[key] in ("", None):
        raise ProfileError(f"{where}: missing required key '{key}'")
    return table[key]


def _fragment(profile_dir: Path, rel: str, where: str) -> str:
    try:
        path = _validate_payload_path(profile_dir.resolve(), rel, require_file=True)
    except ProfileError as exc:
        raise ProfileError(f"{where}: {exc}") from exc
    return path.read_text(encoding="utf-8")


def validate(cfg: dict, profile_dir: Path) -> None:
    unknown = set(cfg) - TOP_LEVEL_KEYS
    if unknown:
        raise ProfileError(f"adapter.toml: unknown top-level keys: {sorted(unknown)}")
    if cfg.get("schema") != SCHEMA_VERSION:
        raise ProfileError(f"adapter.toml: schema must be {SCHEMA_VERSION}")

    project = cfg.get("project")
    if not isinstance(project, dict):
        raise ProfileError("adapter.toml: [project] table is required")
    _require(project, "name", "[project]")
    _require(project, "contract", "[project]")
    _fragment(profile_dir, project["contract"], "[project].contract")
    if not isinstance(project.get("depth_docs", []), list):
        raise ProfileError("[project].depth_docs must be a list")

    orch = cfg.get("orchestrator", {})
    if orch.get("mandate_file"):
        _fragment(profile_dir, orch["mandate_file"], "[orchestrator].mandate_file")

    for i, item in enumerate(cfg.get("do_not_edit", [])):
        _require(item, "path", f"[[do_not_edit]] #{i}")
        _require(item, "reason", f"[[do_not_edit]] #{i}")

    slugs: set[str] = set()
    for i, ins in enumerate(cfg.get("instructions", [])):
        where = f"[[instructions]] #{i}"
        slug = str(_require(ins, "slug", where))
        if not re.fullmatch(r"[a-z0-9-]+", slug):
            raise ProfileError(
                f"{where}: slug '{slug}' must match ^[a-z0-9-]+$; instruction slugs "
                "are file-name components and cannot contain path segments")
        if slug in slugs:
            raise ProfileError(f"{where}: duplicate slug '{slug}'")
        slugs.add(slug)
        _require(ins, "apply_to", where)
        _require(ins, "name", where)
        _require(ins, "description", where)
        _fragment(profile_dir, str(_require(ins, "body", where)), f"{where}.body")

    ids: set[str] = set()
    for i, srv in enumerate(cfg.get("mcp", [])):
        where = f"[[mcp]] #{i}"
        sid = str(_require(srv, "id", where))
        if "url" in srv:
            raise ProfileError(
                f"[[mcp]] entry '{sid}' has a literal 'url' key. MCP URLs are "
                "credentials; remove the key — only ${input:" + sid + "-url} is ever written."
            )
        if sid in ids:
            raise ProfileError(f"{where}: duplicate id '{sid}'")
        ids.add(sid)
        _require(srv, "type", where)
        _require(srv, "input_description", where)

    for i, rule in enumerate(cfg.get("standing_rules", [])):
        _require(rule, "text", f"[[standing_rules]] #{i}")

    hooks = cfg.get("hooks")
    if hooks is not None:
        if not isinstance(hooks, dict):
            raise ProfileError("[hooks] must be a table")
        _require(hooks, "file", "[hooks]")
        if not (hooks.get("pre_tool_use") or hooks.get("session_start")):
            raise ProfileError("[hooks]: at least one of pre_tool_use / session_start is required")
        for key in ("pre_tool_use", "session_start"):
            cmd = hooks.get(key, "")
            if "$CLAUDE_PROJECT_DIR" in cmd or "${CLAUDE_PROJECT_DIR" in cmd:
                raise ProfileError(
                    f"[hooks].{key} relies on $CLAUDE_PROJECT_DIR, which Copilot never sets; "
                    "use a repo-relative command (the hook runs with cwd = workspace root)"
                )

    agents = cfg.get("agents")
    if agents is not None:
        if not isinstance(agents, dict):
            raise ProfileError("[agents] must be a table")
        _require(agents, "source_dir", "[agents]")
        if not isinstance(agents.get("models"), dict) or not agents["models"]:
            raise ProfileError("[agents.models] mapping table (opus/sonnet/haiku -> display name) is required")
        if not isinstance(agents.get("tools"), dict) or not agents["tools"]:
            raise ProfileError("[agents.tools] mapping table (Claude tool -> VS Code tool) is required")
        orch = agents.get("orchestrator")
        if orch is not None:
            for key in ("name", "description", "role_file", "tools"):
                _require(orch, key, "[agents.orchestrator]")
            if orch.get("model") and orch["model"] not in agents["models"]:
                raise ProfileError(f"[agents.orchestrator].model '{orch['model']}' has no entry in [agents.models]")

    names: set[str] = set()
    for i, sk in enumerate(cfg.get("skills", [])):
        where = f"[[skills]] #{i}"
        name = str(_require(sk, "name", where))
        if not re.fullmatch(r"[a-z0-9-]+", name):
            raise ProfileError(f"{where}: name '{name}' must match ^[a-z0-9-]+$ (VS Code skill name rule)")
        if name in names:
            raise ProfileError(f"{where}: duplicate skill name '{name}'")
        names.add(name)
        _require(sk, "description", where)

    exp = cfg.get("export")
    if exp is not None:
        if not isinstance(exp, dict):
            raise ProfileError("[export] must be a table")
        exclude = exp.get("exclude", [])
        if not isinstance(exclude, list) or not all(isinstance(v, str) for v in exclude):
            raise ProfileError("[export].exclude must be a list of repo-relative path strings")
        if not isinstance(exp.get("payload"), list):
            raise ProfileError("[export].payload must be a list of repo-relative path strings "
                               "or { path = \"...\", optional = true } tables")
        patterns = [pat for pat, _optional in payload_patterns(exp)] + list(exclude)
        for item in patterns:
            if item.startswith("/") or ".." in Path(item).parts:
                raise ProfileError(f"[export]: '{item}' must be repo-relative and must not escape the root")
        if not exp.get("payload"):
            raise ProfileError("[export]: payload is required when the table is present")
        if exp.get("exact") is True:
            exact_payload_modes(exp)


def exact_payload_modes(exp: dict) -> dict[str, int]:
    """File and mode allowlist shared by stock export and seed preflight."""
    paths = exp["payload"]
    if any(not isinstance(p, str) or Path(p).as_posix() != p or p == "."
           or "\\" in p or any(ch in p for ch in "*?[") for p in paths):
        raise ProfileError("[export].exact requires literal, normalized file paths")
    if len(set(paths)) != len(paths):
        raise ProfileError("[export].exact contains duplicate file paths")
    executable = exp.get("executable", [])
    if (not isinstance(executable, list) or
        any(not isinstance(p, str) or p not in paths for p in executable)):
        raise ProfileError("[export].executable must only name declared payload files")
    return {p: 0o755 if p in executable else 0o644 for p in paths}


def payload_patterns(exp: dict) -> list[tuple[str, bool]]:
    """``[export].payload`` entries as ``(pattern, optional)`` pairs.

    A plain string is a REQUIRED pattern: ``export`` refuses when it matches
    nothing, because a silently missing payload group ships a kit whose
    generated files point at sources that do not exist. A pattern that may
    legitimately be absent is written ``{ path = "...", optional = true }``
    and only warns.
    """
    out: list[tuple[str, bool]] = []
    for i, item in enumerate(exp.get("payload", [])):
        where = f"[export].payload #{i}"
        if isinstance(item, str):
            if not item:
                raise ProfileError(f"{where}: empty pattern")
            out.append((item, False))
        elif isinstance(item, dict):
            unknown = set(item) - {"path", "optional"}
            if unknown:
                raise ProfileError(f"{where}: unknown keys {sorted(unknown)} (allowed: path, optional)")
            path = item.get("path")
            if not isinstance(path, str) or not path:
                raise ProfileError(f"{where}: 'path' must be a non-empty string")
            optional = item.get("optional", False)
            if not isinstance(optional, bool):
                raise ProfileError(f"{where}: 'optional' must be true or false")
            out.append((path, optional))
        else:
            raise ProfileError(f"{where}: must be a string or a {{ path = ..., optional = ... }} table")
    return out


# --------------------------------------------------------------------------
# Rendering
# --------------------------------------------------------------------------

def substitute(template: str, values: dict[str, str]) -> str:
    out = template
    for key, val in values.items():
        out = out.replace("{{" + key + "}}", val)
    if "{{" in out:
        start = out.index("{{")
        raise ProfileError(f"unresolved template key near: {out[start:start + 40]!r}")
    return out


def _bullet(head: str, tail: str) -> str:
    """Render one list item; continuation lines of a multi-line tail are kept."""
    return f"- {head} — {tail.rstrip()}"


def _join_docs(docs: list[str]) -> str:
    items = [f"`{d}`" for d in docs]
    if len(items) <= 1:
        return "".join(items)
    if len(items) == 2:
        return f"{items[0]} and {items[1]}"
    return ", ".join(items[:-1]) + f", and {items[-1]}"


